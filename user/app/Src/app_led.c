/**
 ******************************************************************************
 * @file    app_led.c
 * @brief   应用层（app）—— LED 闪烁业务实现
 *
 *  ============ 整条 LED 链从这里开始（除 main 之外） ============
 *    app_led_init()      业务：告诉状态机灯闪多快          ← cfg 提供参数
 *        └─ APP_BLINK_Init()           【应用层·闪烁状态机】初始化
 *             └─ PER_LED_Init()              【感知层·统一接口】
 *                  └─ per_gpio_init()             【感知层·GPIO 驱动】
 *                       └─ HAL_GPIO_Init()              【HAL / 硬件】
 *    app_led_task()      每 1ms 喂一次节拍
 *        └─ APP_BLINK_process()        【应用层·闪烁状态机】计毫秒判到点
 *              └─ PER_LED_Toggle()         【感知层·统一接口】
 *                    └─ per_gpio_toggle()        【感知层·GPIO 驱动】
 *                          └─ HAL_GPIO_TogglePin()   【HAL / 硬件】
 *  ===============================================================
 *
 *  本文件是全工程唯一"改需求"的地方：想让哪颗灯闪、闪多快，
 *  都只在这一层表达；改完不需要碰下面任何一层。
 *
 *  接口的完整说明（功能/参数/返回值/调用处/注意事项）写在 app_led.h，
 *  本文件的注释侧重"业务是怎么串起来的"。
 ******************************************************************************
 */
#include "module_cfg.h"
#if APP_LED_ENABLE
#include "app_led.h"
#include "app_blink.h"
#include "cmsis_os.h"  /* FreeRTOS 的 CMSIS-RTOS V2 封装：osDelay / osThreadNew 等 */
#include "FreeRTOS.h"
#include "task.h"      /* FreeRTOS 原生任务 API（头文件按惯例一并包含） */

/*----------------------------------------------------------------------------
 * 函数功能：应用层业务初始化 —— 把灯要闪的速度告诉闪烁状态机
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：本文件 app_led_task() 的开头（任务首次被调度时执行一次）
 *           【接口契约见 app_led.h】
 * 注意事项：① 先初始化引脚，再设周期，顺序不能反：
 *              引脚没配好就设周期，灯不会亮（但程序也不会报错）
 *           ② 这里的周期直接来自 cfg 的宏，属于"编译期配置"：
 *              改 cfg_param.h 后必须重新编译才能生效（不是在线可调的）
 *           ③ 两处调用的返回值都被有意丢弃：宏是常量、编号是常量，正常不会失败；
 *              若将来改成从串口读周期，就应检查返回值
 *           ④ 本函数是一次性上电配置，不可放进 for(;;) 里
 *----------------------------------------------------------------------------*/
void app_led_init(void)
{
    /* 初始化闪烁状态机的灯（会一路转发到感知层，把 PG14 配成推挽输出） */
    APP_BLINK_Init();

    /* 设置 LED1 闪烁半周期：500ms 半周期 → 亮 500ms + 灭 500ms = 1Hz */
    APP_BLINK_blink_set(APP_BLINK_LED1, APP_LED1_BLINK_MS);
}

/*----------------------------------------------------------------------------
 * 函数功能：LED 应用任务体 —— 循环给状态机喂 1ms 节拍，驱动灯闪烁
 * 参数    ：argument —— 任务参数，未使用（创建时传的是 NULL）
 * 返回值  ：无（死循环，永不返回）
 * 调用处  ：由 FreeRTOS 调度器调用（app_task.c 里 osThreadNew 注册进来的）
 *           【接口契约见 app_led.h】
 * 注意事项：① (void)argument 是为了消掉编译器"参数未使用"的告警，
 *              同时明确告诉读者"这个参数我不用"，比直接删掉参数名更清晰
 *           ② app_led_init() 放在循环外，只执行一次；
 *              如果误放进 for 循环里，灯会被反复复位，永远闪不起来
 *           ③ ★ 循环的最后一定不能少了 osDelay()：
 *              没有它，本任务会一直占着 CPU，其它任务（包括 defaultTask）
 *              永远得不到执行，表现为"程序像卡死了"
 *           ④ osDelay(APP_BLINK_TICK_MS) 的值就是节拍精度。
 *              FreeRTOSConfig.h 里节拍为 1000Hz，所以 osDelay(1) 正好是 1ms；
 *              改成 10 会让闪烁慢到 1/10
 *           ⑤ 实际间隔会比 1ms 略长（调度开销、其它任务抢占），
 *              属于正常现象；对 LED 闪烁这种应用，毫秒级抖动完全可以忽略
 *----------------------------------------------------------------------------*/
void app_led_task(void *argument)
{
    (void)argument;  /* 显式丢弃未使用参数，避免编译器告警 */

    /* 任务启动后先走一遍初始化链（只走一次） */
    app_led_init();

    /* 无限循环，任务主体 */
    for (;;)
    {
 #if APP_LED_TASK_ENABLE       
        /* 推进闪烁状态机：数 1 个毫秒 */
        APP_BLINK_process();
#endif
        /* 延时 1ms：既是让出 CPU，也是状态机的节拍
         * FreeRTOSConfig.h 里节拍为 1000Hz，所以 osDelay(1) 正好是 1ms */
        osDelay(APP_BLINK_TICK_MS);
    }
}

#endif /* APP_LED_ENABLE */
