/**
 ******************************************************************************
 * @file    app_watchdog.h
 * @brief   应用层（app）—— 看门狗喂狗任务与卡死演示
 *
 *  业务就四件事（与课件 2.4 一致）：
 *    ① 上电先报"上次怎么复位的"（IWDG watchdog / power-on & others）
 *    ② 启动 IWDG（超时 3 秒，参数在 cfg_param.h），随后每 500 ms 喂一次
 *    ③ 每 2 秒打一行 [WDT] Alive, feed=N —— 证明"狗一直有人喂"
 *    ④ 卡死演示：串口敲 HANG → 本任务不再喂狗 → 约 3 秒后 IWDG 复位整机
 *
 *  调用链（每 500 ms 走一遍，两跳）：
 *    app_watchdog_task → PER_IWDG_Feed（perception）→ HAL_IWDG_Refresh → IWDG 硬件
 *  打印借串口链出口（MOD_UART1_*），与 app_dht11 同一条跨链依赖。
 *
 *  与课件 2.4 的两处适配（课件板有按键、本板没有）：
 *    - 课件的卡死演示是"按 KEY0"；本板（STM32F407ZET6）没有多余按键，
 *      改用串口命令 HANG 触发——顺带把串口链也验了一遍
 *    - 课件的 IWDG 初始化在 CubeMX 生成的 iwdg.c；本工程收进感知层
 *      per_iwdg（参数进 cfg），Core 保持原样
 ******************************************************************************
 */
#ifndef APP_WATCHDOG_H
#define APP_WATCHDOG_H

/*----------------------------------------------------------------------------
 * 函数功能：看门狗喂狗任务（FreeRTOS 任务体，永不返回）
 * 参数    ：argument —— 任务参数，本例未用（传 NULL）
 * 返回值  ：无
 * 调用处  ：app_task.c 的 app_taskCreate()，经 osThreadNew 登记（最后一个创建）
 * 注意事项：① 任务开头先"读复位原因 → 清标志 → 启动 IWDG → 喂第一口"，
 *              顺序不能乱：先清标志就读不到东西，先启动狗就来不及读
 *           ② 打印前两行（复位原因 + 启动行）之前会 osDelay 一小段，
 *              等串口任务把 MOD_UART1 链路拉起来——否则启动行会丢；
 *              这段延时远小于 3 秒超时，不会咬狗
 *           ③ 收到 HANG 演示请求后打印一行随即进入死循环：
 *              本任务不再喂狗，约 3 秒后 IWDG 复位整机；
 *              与其平级的其它任务仍在轮转（LED 照闪），
 *              演示的是"一个任务卡死、看门狗把整机救回来"
 *----------------------------------------------------------------------------*/
void app_watchdog_task(void *argument);

/*----------------------------------------------------------------------------
 * 函数功能：请求一次卡死演示（只置标志，真正的"卡死"在看门狗任务里执行）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：app_cmd.c 的 HANG 命令（同层调用，与 app_cmd → APP_BLINK_* 同级）
 * 注意事项：① 为什么不在 app_cmd 里直接死循环：
 *              卡死串口任务会连"复位前的最后一行打印"都发不完整，
 *              而且演示目的不同——课件演示的是"喂狗的人罢工了"，
 *              所以让看门狗任务自己卡住，语义更干净
 *           ② 本函数只置一个 volatile 标志，可随时调用、无副作用；
 *              一旦生效系统约 3 秒后复位，该标志也随之消失（RAM 重来）
 *----------------------------------------------------------------------------*/
void APP_WATCHDOG_HangDemo(void);

#endif /* APP_WATCHDOG_H */
