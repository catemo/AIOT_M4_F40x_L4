/**
 ******************************************************************************
 * @file    app_link.h
 * @brief   应用层（app）—— 阈值联动规则（温度 → LED1，湿度 → LED2）
 *
 *  本文件只有一件事：把"读到的数"变成"灯的动作"。
 *
 *  ★ 为什么单独成一个模块，而不是写进 app_dht11.c：
 *    采集说"现在 29 度"，联动说"29 度该亮灯"。这两句话的变化频率完全不同——
 *    传感器换型号（DHT11 → DHT22）不会动联动一行代码；
 *    改阈值、改联动对象（比如改成"超温就蜂鸣器响"）也不会碰采集。
 *    分开写，改一边不动另一边。
 *
 *  ★ 阈值放在哪：在 cfg 横切层的 cfg_param.h（APP_LINK_TEMP_THRESHOLD /
 *    APP_LINK_HUMI_THRESHOLD），本文件一个字面量都不写。
 *    想改行为就改那两行，不用读懂判定逻辑 —— 这条规矩的目的就是
 *    让"调参的人"和"写代码的人"可以是两个不同的人。
 *
 *  ★ 本层依赖：只依赖感知层的 per_led（借用点灯接口）。
 *    它属于 DHT11 链，却要借 LED 链的下半段 —— 这条跨链依赖
 *    在 cfg_check.h 里有一条专门的闸门看着（APP_LINK requires PER_LED）。
 ******************************************************************************
 */
#ifndef APP_LINK_H
#define APP_LINK_H

#include <stdint.h>

/*----------------------------------------------------------------------------
 * 函数功能：联动初始化（确保要用到的 LED 硬件已就绪，并进入确定状态）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：app_dht11.c 任务开头（完整链：app_dht11_task → 本函数）
 * 注意事项：① 为什么这里还要调一次 PER_LED_Init()：
 *              本工程还有一种形态是"关掉自动闪烁、只留联动"
 *              （APP_LED_ENABLE 末尾改 0）。那样就没有人再走到
 *              app_led_init → APP_BLINK_Init → PER_LED_Init 这条链了，
 *              联动自己必须保证灯引脚是配好的 —— 否则两颗灯全程不亮，
 *              看起来就像联动逻辑写错了。
 *              PER_LED_Init 是幂等的，被 LED 链调过一次也不冲突。
 *           ② 初始化后主动把两颗灯熄灭：进入联动前的状态必须是确定的。
 *              否则上电瞬间灯是灭是亮取决于引脚复位值，"第一拍"是不可预期的
 *----------------------------------------------------------------------------*/
void APP_LINK_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：按温度阈值联动 LED1（≥ 阈值点亮，否则熄灭）
 * 参数    ：temp_int —— 温度整数部分（℃）
 * 返回值  ：无
 * 调用处  ：app_dht11.c 读取成功后
 * 注意事项：① ★ 为什么只传整数部分：DHT11 的分辨率就是 1 ℃，
 *              小数部分恒为 0，整数比较与"×10 后比较"完全等价。
 *              不做无谓的精度，也不制造"看起来很精确"的假象
 *           ② 阈值是 >= 而不是 >：课件定的是"温度 ≥28℃ 点亮"，
 *              边界值算在触发一侧（警戒语义：宁可早一点提醒）
 *           ③ 本函数不做"读失败怎么办"的判断 —— 那是调用方的事。
 *              读失败时 app_dht11 根本不会调用本函数，灯自然保持现状
 *              （这就是"故障安全"：没有输入就没有动作，绝不误动作）
 *----------------------------------------------------------------------------*/
void APP_LINK_ApplyTemp(uint8_t temp_int);

/*----------------------------------------------------------------------------
 * 函数功能：按湿度阈值联动 LED2（≥ 阈值点亮，否则熄灭）
 * 参数    ：hum_int —— 湿度整数部分（%RH）
 * 返回值  ：无
 * 调用处  ：app_dht11.c 读取成功后
 * 注意事项：与 APP_LINK_ApplyTemp() 完全对称：湿度 → LED2(PG13)，温度 → LED1(PG14)
 *----------------------------------------------------------------------------*/
void APP_LINK_ApplyHum(uint8_t hum_int);

#endif /* APP_LINK_H */
