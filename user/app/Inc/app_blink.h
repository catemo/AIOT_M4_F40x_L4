/**
 ******************************************************************************
 * @file    app_blink.h
 * @brief   应用层（app）—— LED 闪烁服务（1 颗灯：LED1）
 *
 *  本文件职责：实现"功能"，也就是"闪烁"这件事本身，但不知道具体是哪块板子。
 *    - 每颗 LED 一个独立的闪烁计时器：数够半周期就翻转一次
 *    - 谁去数？由 app_led 的任务每 APP_BLINK_TICK_MS（当前 10ms）
 *      调一次 APP_BLINK_process()
 *      （这个"固定节拍"约定就是本文件对上层的要求）
 *
 *  三者的分工：
 *    app_led.c            业务：决定"哪颗灯、闪多快"
 *    app_blink.c（本文件）功能：实现"怎么闪"（状态机心脏）
 *    per_led / per_gpio   硬件：负责"点亮引脚"
 *
 *  ★ 本文件只 include per_led.h，绝不 include per_gpio.h。
 ******************************************************************************
 */
#ifndef APP_BLINK_H
#define APP_BLINK_H

#include <stdint.h>

/* ===================== LED 编号（状态机内部独立定义，屏蔽下层） ===================== */
/**
 * @brief 闪烁状态机的 LED 编号，和 per_led 的编号互相独立（解耦）
 * @note  各自一套编号是刻意的：任何一侧增删灯具，都不影响其它侧的枚举值；
 *        APP_BLINK_LED_COUNT 放在最后，既用于越界判断，也用于内部状态数组的长度
 */
typedef enum
{
    APP_BLINK_LED1 = 0,   /* LED1（硬件：PG14） */
    APP_BLINK_LED_COUNT   /* 哨兵：灯的总数（本例 = 1） */
} APP_BLINK_LED_t;

/* ===================== 返回码 ===================== */
#define APP_BLINK_OK        0   /* 成功 */
#define APP_BLINK_ERR_PARAM 1   /* 参数错误（编号越界，或半周期传 0） */

/*----------------------------------------------------------------------------
 * 函数功能：初始化 LED 硬件（转发感知层 PER_LED_Init，最终落到 per_gpio 的引脚配置）
 * 参数    ：无
 * 返回值  ：APP_BLINK_OK(0) = 成功（下层返回码原样上抛）
 * 调用处  ：app_led.c 的 app_led_init()
 * 注意事项：① 必须在 APP_BLINK_blink_set / APP_BLINK_process 之前调用；
 *              引脚没初始化就点灯，写寄存器全部无效
 *           ② 本工程 GPIO 初始化的完整链路：
 *              app_led_init → APP_BLINK_Init → PER_LED_Init → per_gpio_init，
 *              每层各过一手、谁也不越级——这是"命令只许往下传"
 *              在初始化上的体现
 *----------------------------------------------------------------------------*/
uint8_t APP_BLINK_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：设置某颗 LED 的闪烁半周期（决定闪多快）
 * 参数    ：led            —— 状态机 LED 编号，取值 APP_BLINK_LED1(0)
 *           half_period_ms —— 半周期，单位毫秒：每过这么久把灯翻转一次
 *                             半周期 500ms → 亮 500ms、灭 500ms → 1Hz 闪烁
 *                             半周期 250ms → 2Hz 闪烁（闪得更快）
 * 返回值  ：APP_BLINK_OK(0) = 设置成功
 *           APP_BLINK_ERR_PARAM(1) = 编号越界，或 half_period_ms 传了 0
 * 调用处  ：app_led.c 的 app_led_init()，上电时对灯调一次
 *           参数来自 cfg 横切层的 APP_LED1_BLINK_MS
 * 注意事项：① half_period_ms = 0 被认为"参数非法"并被拒绝，不会把灯设成"不闪"；
 *              若将来真的要"停闪"，应另加 stop 接口，不要靠传 0
 *           ② 本函数会把该灯的计时器清零，所以灯从"灭"开始数第一个半周期
 *           ③ 闪烁只在 APP_BLINK_process() 被周期性调用后才会真正动起来；
 *              只调本函数而不调 APP_BLINK_process()，灯会一直是灭的
 *           ④ 想做"跑马灯""呼吸灯"等新特效，就在本文件加新函数，
 *              不要动感知层，也不要在应用业务里拼凑时序
 *----------------------------------------------------------------------------*/
uint8_t APP_BLINK_blink_set(APP_BLINK_LED_t led, uint16_t half_period_ms);

/*----------------------------------------------------------------------------
 * 函数功能：LED 闪烁周期处理 —— 给每颗灯计毫秒，到点就翻转它（闪烁的心脏）
 * 参数    ：无
 * 返回值  ：APP_BLINK_OK(0)（固定返回成功；本函数不做参数校验，不会失败）
 * 调用处  ：app_led.c 的 app_led_task() 任务循环里，每 APP_BLINK_TICK_MS
 *           （当前 10ms）调一次
 *           （完整调用链：app_led_task → APP_BLINK_process →
 *             PER_LED_Toggle → per_gpio_toggle → HAL_GPIO_TogglePin）
 * 注意事项：① ★ 必须由"固定节拍"调用（cfg_param.h 的 APP_BLINK_TICK_MS，
 *              当前 10ms），这是本文件对上层唯一的硬要求。
 *              调得太慢（比如 osDelay 写大了），闪烁会整体变慢；
 *              调得太快，闪烁会整体变快；忽快忽慢则闪烁节奏会抖动。
 *              节拍从 1ms 放宽到 10ms（2026-10-30）：半周期 500ms 下
 *              肉眼无差别，LED 任务唤醒降为 1/10。
 *           ② 本函数是"非阻塞"的：进去就出来，不做任何延时，
 *              所以放在任务循环里不会影响同一任务的其它工作
 *           ③ 只有被 APP_BLINK_blink_set() 设置过的灯才会动，
 *              其它灯被跳过（continue），不做无谓操作
 *           ④ 内部通过 PER_LED_Toggle() 操作灯，绝不直接碰 GPIO
 *----------------------------------------------------------------------------*/
uint8_t APP_BLINK_process(void);

/*----------------------------------------------------------------------------
 * 函数功能：点亮某颗 LED 并让它退出闪烁（串口控灯章节新增）
 * 参数    ：led —— 状态机 LED 编号，取值 APP_BLINK_LED1(0)
 * 返回值  ：APP_BLINK_OK(0) = 成功；APP_BLINK_ERR_PARAM(1) = 编号越界
 * 调用处  ：app_cmd.c 的 cmd_exec()（串口命令 "LED1 ON"）
 * 注意事项：① ★ 手动与闪烁互斥：点亮 = 先把这颗灯的半周期清 0
 *              （状态机从此跳过它），再去点灯；否则状态机会跟串口命令抢灯，
 *              表现为"刚点亮又自己灭了"
 *           ② 顺序是关键：先停闪、再点灯。反过来的话，两步之间
 *              可能正好被 APP_BLINK_process() 插一脚翻转一次
 *----------------------------------------------------------------------------*/
uint8_t APP_BLINK_On(APP_BLINK_LED_t led);

/*----------------------------------------------------------------------------
 * 函数功能：熄灭某颗 LED 并让它退出闪烁（串口控灯章节新增）
 * 参数    ：led —— 状态机 LED 编号，取值 APP_BLINK_LED1(0)
 * 返回值  ：APP_BLINK_OK(0) = 成功；APP_BLINK_ERR_PARAM(1) = 编号越界
 * 调用处  ：app_cmd.c 的 cmd_exec()（串口命令 "LED1 OFF"）
 * 注意事项：与 APP_BLINK_On() 完全对称，差别只在最后调 PER_LED_Off()
 *----------------------------------------------------------------------------*/
uint8_t APP_BLINK_Off(APP_BLINK_LED_t led);

/*----------------------------------------------------------------------------
 * 函数功能：查询某颗 LED 的真实亮灭（串口控灯章节新增）
 * 参数    ：led —— 状态机 LED 编号，取值 APP_BLINK_LED1(0)
 * 返回值  ：1 = 亮；0 = 灭（越界返回 0）
 * 调用处  ：app_cmd.c 的 cmd_exec()（串口命令 "STATUS"）
 * 注意事项：读的是真实引脚电平（一路问到 per_gpio），本层不缓存状态——
 *           闪烁中的灯也能查出它"此刻"是亮是灭
 *----------------------------------------------------------------------------*/
uint8_t APP_BLINK_IsOn(APP_BLINK_LED_t led);

#endif /* APP_BLINK_H */
