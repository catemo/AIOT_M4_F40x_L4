/**
 ******************************************************************************
 * @file    app_hex_cmd.h
 * @brief   应用层（app）—— 十六进制帧执行器：功能码 → 寄存器 → 动作 → 应答帧
 *
 *  分工：
 *    protocol_hex.c   只管"字节怎么拼成帧"（帧格式 + CRC8）
 *    本文件           只管"帧里的功能码/寄存器是什么意思"（业务语义）
 *    app_cmd.c        只管"从哪读字节、应答往哪发"（通道）
 *  三者拆开的好处：同一套执行器可以被串口、RS485、MQTT 桥接复用，
 *  换通道不用改一行业务判断。
 *
 *  分层纪律：
 *    点 LED1 → APP_BLINK_On / Off / IsOn（同层闪烁状态机，先停闪再点灯）
 *    点 LED2 → PER_LED_On / Off / IsOn（与 app_link 同一种"应用层直达感知层"）
 *    读温湿度 → APP_DHT11_GetSnapshot（快照，不触发新采集）
 *    写阈值   → APP_PARAM_SetThresholds（更新 RAM + 写 EEPROM + 读回确认）
 *    本文件绝不直接碰 GPIO，也绝不 include net_uart / mod_uart1。
 *
 *  ★ 与文本协议的共存由 app_cmd.c 负责：每字节先喂帧解析器，
 *    只有"不是帧头且不在收帧中"的字节才轮到文本行解析器。
 ******************************************************************************
 */
#ifndef APP_HEX_CMD_H
#define APP_HEX_CMD_H

#include <stdint.h>

/*----------------------------------------------------------------------------
 * 函数功能：执行一帧请求，必要时生成应答帧
 * 参数    ：in_frame  —— 8 字节请求帧（调用方保证 CRC 已通过）
 *           out_frame —— 8 字节应答缓冲（需要应答时被填满）
 * 返回值  ：1 = 需要发送应答（out_frame 已填好）
 *           0 = 不需要应答（广播地址 / 地址不是本机 / 传感器上报帧）
 * 调用处  ：app_cmd.c 的 app_cmd_task()，ProtoHex_Feed 返回 FRAME 时调用
 * 注意事项：① **广播地址(0x0)照常执行动作，但不填应答**；地址既非 0 也非本机的
 *              帧整帧丢弃。这是总线上多设备共存的基本礼仪，避免应答碰撞
 *           ② 读寄存器成功回 READ_REG + 值；非法地址回 ERROR(0x02)
 *           ③ 写寄存器成功回 ACK(0xEE)，失败回 ERROR(对应错误码)
 *           ④ LED 状态本工程不落 EEPROM（参数块没有 led_state 字段），
 *              上电后由闪烁与联动重新决定——这一点与参考工程不同，文档里有说明
 *----------------------------------------------------------------------------*/
uint8_t APP_HexCmd_Process(const uint8_t *in_frame, uint8_t *out_frame);

/*----------------------------------------------------------------------------
 * 函数功能：为"CRC 错的帧"生成 ERROR(0x04) 应答
 * 参数    ：bad_frame —— 8 字节原始帧（第 8 字节已确认算错，前 7 字节仍可用）
 *           out_frame —— 8 字节应答缓冲
 * 返回值  ：1 = 需要发送；0 = 不该应答（广播 / 非本机地址）
 * 调用处  ：app_cmd.c 的 app_cmd_task()，ProtoHex_Feed 返回 CRC_ERROR 时调用
 * 注意事项：应答里的 REG / SEQ 取自信任的前 7 字节：主站靠 SEQ 配对，
 *           靠 REG 知道是哪次写翻车；DATA 固定 PROTO_HEX_ERR_CRC
 *----------------------------------------------------------------------------*/
uint8_t APP_HexCmd_BuildCrcError(const uint8_t *bad_frame, uint8_t *out_frame);

#endif /* APP_HEX_CMD_H */
