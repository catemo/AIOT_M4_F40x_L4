/**
 ******************************************************************************
 * @file    app_oled.h
 * @brief   应用层（app）—— OLED 显示业务接口（2.9 新增）
 *
 *  本层只决定"显示什么、放第几行、什么时候刷"，不关心 I2C 怎么翻转、
 *  SSD1306 的显存怎么组织（那些在 platform/mod_oled.c 与 network/net_i2c_sw.c）。
 *
 *  四行布局（8x16 大字，每字符占 2 页）：
 *    页 0-1  Temp: 26.9 C      ← DHT11 任务每 2 s 刷一次
 *    页 2-3  Hum:  36.0 %      ← DHT11 任务每 2 s 刷一次
 *    页 4-5  Light: 3027       ← 光敏任务每 500 ms 刷一次
 *    页 6-7  Level: DARK       ← 光敏任务每 500 ms 刷一次
 *
 *  ★ 两个任务写一块屏，必须串行化：DHT11 任务与光敏任务都调本层接口，
 *    每条刷新都在【互斥锁】里完成（100 ms 超时，拿不到就放弃本帧）。
 *    没有这把锁，两条 I2C 事务交叠 = 花屏 / 丢字。
 *
 *  ★ 刷新一律"整行定宽覆盖"：先在栈上把字符串拼成固定宽度（空格补齐）再上屏，
 *    这样 9→10、999→1000 这类位数变化不会残留旧字符。
 *
 *  ★ 本层刻意不引 printf / snprintf：本工程全程不引格式化库（省几 KB FLASH），
 *    数字转字符串用手写的几十行（见 app_oled.c）。
 ******************************************************************************
 */
#ifndef APP_OLED_H
#define APP_OLED_H

#include <stdint.h>

/*----------------------------------------------------------------------------
 * 函数功能：创建 OLED 写互斥锁（全局唯一）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：app_task.c 的 app_taskCreate()，创建任务之前（调度器启动前）
 * 注意事项：① 必须在 APP_OLED_Init() 之前调用：初始化也会写屏（自检与静态标签）
 *           ② 创建失败（堆内存不足）时不报错：后续写操作检测到 NULL 直接放行，
 *              功能仍可用，只是失去并发保护（比整机停在一个显示屏上好）
 *----------------------------------------------------------------------------*/
void APP_OLED_CreateMutex(void);

/*----------------------------------------------------------------------------
 * 函数功能：OLED 初始化：器件初始化 → 全屏点亮 500 ms 自检 → 清屏 → 静态标签
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：app_task.c 的 app_taskCreate()（互斥锁创建之后、建任务之前）
 * 注意事项：① ★ 全屏点亮是"一次自检三件事"：I2C 通、供电足、像素全好；
 *              屏若只亮一部分，先查对比度 / VCOM / 预充电参数
 *           ② 静态标签只写一次（Temp/Hum/Light/Level 与占位符），
 *              后面的周期刷新只覆盖数值部分——整屏重绘既慢又闪
 *           ③ 本函数会忙等约 600 ms（电荷泵 100 ms + 自检 500 ms），
 *              此时调度器还没启动，没有任务被耽误
 *----------------------------------------------------------------------------*/
void APP_OLED_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：刷新温湿度两行（8x16 大字）
 * 参数    ：temp_int/temp_dec —— 温度整数/小数位
 *           humi_int/humi_dec —— 湿度整数/小数位
 * 返回值  ：无
 * 调用处  ：app_dht11.c 每轮采集成功后
 * 注意事项：① 拿不到锁（100 ms 超时）就放弃本帧，下个周期再刷——
 *              宁可少刷一帧，也不让两条 I2C 事务交叠
 *           ② 两行在同一把锁里一起刷：中间不会被另一个任务插进来
 *----------------------------------------------------------------------------*/
void APP_OLED_UpdateTempHum(uint8_t temp_int, uint8_t temp_dec,
                            uint8_t humi_int, uint8_t humi_dec);

/*----------------------------------------------------------------------------
 * 函数功能：刷新光照两行（8x16 大字）
 * 参数    ：adc —— 滤波后的 ADC 值（0~4095）
 *           level_str —— 等级文本（"DARK"/"MEDIUM"/"BRIGHT"，不足 6 字符补空格）
 * 返回值  ：无
 * 调用处  ：app_light.c 每轮分级之后（与控灯同拍）
 * 注意事项：level_str 为 NULL 时显示 "------"（避免空指针把屏幕写花）
 *----------------------------------------------------------------------------*/
void APP_OLED_UpdateLight(uint16_t adc, const char *level_str);

/*----------------------------------------------------------------------------
 * 函数功能：温湿度两行显示 "ERROR"（DHT11 本轮读失败时）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：app_dht11.c 的失败分支
 * 注意事项：★ 只覆盖 Temp/Hum 两行，不动 Light/Level：
 *           一个传感器坏了，另一个照常显示——故障隔离在"行"这一级
 *----------------------------------------------------------------------------*/
void APP_OLED_ShowError(void);

#endif /* APP_OLED_H */
