/**
 ******************************************************************************
 * @file    app_cmd.h
 * @brief   应用层（app）—— 串口命令解析接口（串口控灯的业务端）
 *
 *  本文件是"串口控灯"这条链的业务端：把串口收到的一行字符，
 *  翻译成"灯该做什么"。整条链的分工：
 *
 *      app_cmd       （本文件）语义：一行命令 → 一个动作
 *        ↓
 *      MOD_UART1_*   【platform】入口：与硬件无关的收 / 发名字
 *        ↓
 *      net_uart_*    【network】字节流：DMA 循环 + IDLE 判帧 + 环形缓冲
 *
 *  为什么解析写在应用层而不写进平台层？
 *    "字符串命令长什么样"是业务约定（导演定台词本格式），不是传输能力。
 *    换一套协议（比如 Hex 帧、JSON、MQTT 主题），只改本文件，
 *    platform / network 两行不动。
 *
 *  支持的命令（大小写不限，回车结束）：
 *      LED1 ON / LED1 OFF    点亮 / 熄灭 LED1（PG14）
 *      BLINK                 恢复 1Hz 闪烁（半周期来自 cfg）
 *      STATUS                查询 LED1 真实电平状态
 *      HELP                  打印帮助
 ******************************************************************************
 */
#ifndef APP_CMD_H
#define APP_CMD_H

#include <stdint.h>

/*----------------------------------------------------------------------------
 * 函数功能：串口命令任务体 —— 收字节、攒成行、翻译成动作并回应
 * 参数    ：argument —— 任务参数，未使用（创建时传 NULL）
 * 返回值  ：无（死循环，永不返回）
 * 调用处  ：由 FreeRTOS 调度器调用（app_task.c 里 osThreadNew 注册进来的）
 * 注意事项：① 必须先于任何命令到达之前被调度起来：
 *              它内部会先 MOD_UART1_Init() 把 DMA 接收链路拉起来，
 *              这个任务没跑，串口就一个字节都收不到
 *           ② 循环里不阻塞等待数据：读不到就 osDelay(1) 让出 CPU，
 *              这与 app_led_task 的 1ms 节拍互不干扰
 *           ③ ★ 与 app_led_task 共享"闪烁状态机"：
 *              本任务执行 ON/OFF/BLINK 会改写 app_blink 里的状态数组，
 *              而 app_led_task 每 1ms 读它推进状态机——
 *              本例刻意不加互斥量（uint16_t 对齐读写是原子的，最坏抖动 1ms，
 *              对闪烁节奏无影响）；若将来状态变复杂，应在应用层内加互斥保护
 *----------------------------------------------------------------------------*/
void app_cmd_task(void *argument);

#endif /* APP_CMD_H */
