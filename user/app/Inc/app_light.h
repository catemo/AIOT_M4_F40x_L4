/**
 ******************************************************************************
 * @file    app_light.h
 * @brief   应用层（app）—— 光敏传感器周期采集任务接口（2.8 新增）
 *
 *  本层是光敏链的"业务侧"：决定多久读一次、读到的数意味着什么、灯该怎么亮。
 *  与之对应的感知层 per_light 只管"把 PA5 上的电压变成 0~4095 的数字"。
 *
 *  等级判定（方向不能反！光越强 → 光敏阻值越小 → ADC 越小）：
 *    ADC <  200        → BRIGHT 强光 → LED1 灭、LED2 灭
 *    200 <= ADC < 500  → MEDIUM 中等 → LED1 灭、LED2 亮
 *    ADC >= 500        → DARK   暗光 → LED1 亮、LED2 亮
 *
 *  ★ LED1 为什么要经 APP_BLINK_On/Off 而不是直接 PER_LED：
 *    本工程 LED1 平时由 app_led 的 1 Hz 闪烁状态机驱动。直接写引脚会被
 *    状态机下一个节拍翻转掉，表现为"点亮又自己灭了"。走 APP_BLINK_On/Off
 *    会先把该灯的半周期清 0（退出闪烁），再点灯——与串口控灯是同一条纪律。
 *    LED2 不参与闪烁，直接走 PER_LED 即可。
 *
 *  ★ 与参考工程 L5_xd 的差异：
 *    L5_xd 有 EEPROM 参数块，能做 Q8 增益校准（light_adc_gain/offset）；
 *    本工程参数块没有这两个字段，所以只做 4 点滑动平均，不做校准。
 *    阈值方向与打印格式与课件 2.8 保持一致。
 *
 *  ★ 与 DHT11 联动的边界：
 *    app_link 也会按温度/湿度写两颗灯，与光敏控灯是两套独立的"写灯者"，
 *    同一时刻谁最后写谁生效。两套逻辑都开着时现象是"灯随更近的一次判定变化"，
 *    联调时若只想看光照，把 APP_LINK_ENABLE 改 0 即可。
 ******************************************************************************
 */
#ifndef APP_LIGHT_H
#define APP_LIGHT_H

#include <stdint.h>

/* ===================== 光照等级 ===================== */
/**
 * @brief 光照等级（数值与课件一致：0 强光、1 中等、2 暗光）
 * @note  等级判定的方向由硬件决定：光敏电阻接地，光越强 ADC 越小。
 */
typedef enum
{
    APP_LIGHT_LEVEL_BRIGHT = 0,   /* 强光：ADC <  APP_LIGHT_TH_LOW          */
    APP_LIGHT_LEVEL_MEDIUM = 1,   /* 中等：ADC >= TH_LOW 且 < TH_HIGH      */
    APP_LIGHT_LEVEL_DARK   = 2    /* 暗光：ADC >= APP_LIGHT_TH_HIGH        */
} APP_LIGHT_Level_t;

/* ===================== 最近一次采集的快照 =====================
 * ★ 与 DHT11 快照同一个用意：采集任务写、别的任务只读，两边互不等待。
 *   本册暂不并入 MQTT 上报，接口先留好——将来要上云只需在 app_mqtt 里读它。
 * ★ 结构小且字段对齐（2 个 uint16 + 2 个 uint8），整体拷贝不会读到半截。 */
typedef struct
{
    uint16_t adc;      /* 滤波后的 12 位 ADC 值（0~4095） */
    uint16_t mv;       /* 对应电压（mV，0~3300）          */
    uint8_t  level;    /* APP_LIGHT_Level_t                */
    uint8_t  valid;    /* 1 = 至少成功采集过一次            */
} APP_LIGHT_Snapshot_t;

/*----------------------------------------------------------------------------
 * 函数功能：光敏采集任务体（永不返回）
 * 参数    ：argument —— CMSIS-RTOS2 任务参数槽（本任务不用，恒为 NULL）
 * 返回值  ：无
 * 调用处  ：app_task.c 的 app_taskCreate() 里由 osThreadNew 登记
 * 注意事项：① 传函数名而不是调用它：osThreadNew(app_light_task, ...)
 *           ② 每 APP_LIGHT_PERIOD_MS（500 ms）一轮：读一次 → 4 点平均 →
 *              分级 → 控灯 → 更新快照 → 打印一行 → osDelay
 *           ③ 优先级与其余任务同为 1（平级），500 ms 周期用 osDelay 让出 CPU
 *           ④ ★ 它会接管 LED1 与 LED2：LED1 退出 1 Hz 闪烁，改由光照等级控制
 *----------------------------------------------------------------------------*/
void app_light_task(void *argument);

/*----------------------------------------------------------------------------
 * 函数功能：取最近一次采集的快照（只读，不触发新采集）
 * 参数    ：out —— 输出结构（NULL 时直接返回）
 * 返回值  ：无
 * 调用处  ：预留给上云任务（本册未接入）
 * 注意事项：valid = 0 表示还没采到过有效数据（刚上电的头几百毫秒）
 *----------------------------------------------------------------------------*/
void APP_LIGHT_GetSnapshot(APP_LIGHT_Snapshot_t *out);

#endif /* APP_LIGHT_H */
