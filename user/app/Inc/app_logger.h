/**
 ******************************************************************************
 * @file    app_logger.h
 * @brief   应用层（app）—— W25Q64 环形日志（2.3 外部存储器新增）
 *
 *  日志链的业务侧："记什么、记在哪、满了怎么办"。这一层装的知识：
 *    分区布局（头扇区 + 日志区）/ 记录格式 / 环形回绕与"写满擦最旧"决策。
 *  擦编程的指令序列属于 mod_flash；片选与时序属于 net_spi。
 *
 *  分区（对应课件 22 页）：
 *    0x000000 · 4 KB      参数头：magic + 版本（标识"这片 8MB 归日志用"）
 *    0x001000 · 4KB×2047  日志区：一条 8 B × 512 条 / 扇区，顺序写
 *
 *  ★ 三条行为承诺：
 *    断电接着写 —— 上电扫描日志区找第一个空位（首字节 0xFF 的记录），
 *                  不重头记；记录号 seq 接着涨；
 *    写满擦最旧 —— 要写的位置不是空的（环形回到旧数据），整扇区重擦；
 *    读 0 即最新 —— Read(0) 返回最新一条，上层不关心写指针在哪。
 ******************************************************************************
 */
#ifndef APP_LOGGER_H
#define APP_LOGGER_H

#include <stdint.h>
#include "module_cfg.h"

/* ---- 返回值 ---- */
#define APP_LOGGER_OK          0
#define APP_LOGGER_ERR_NO_DEV -1   /* W25Q64 不在线/型号不符：日志自降级 */
#define APP_LOGGER_ERR_PARAM  -2   /* 读越界（index ≥ 记录数） */
#define APP_LOGGER_ERR_IO     -3   /* 擦/写/读失败：查硬件 */
#define APP_LOGGER_ERR_VERIFY -4   /* 写读不一致：查擦写时序 */

/* ---- 一条记录 8 字节（对应课件 22 页） ---- */
#pragma pack(push, 1)
typedef struct {
    uint32_t tick_s;      /* 上电秒数：开机多久记的        */
    int16_t  temp_x10;    /* 温度 ×10，如 318 = 31.8 ℃    */
    uint16_t humi_x10;    /* 湿度 ×10                      */
    uint16_t seq;         /* 记录号：环形覆盖的依据        */
} app_log_rec_t;          /* 4 KB 扇区装 512 条            */
#pragma pack(pop)

#if APP_LOGGER_ENABLE
/*----------------------------------------------------------------------------
 * 函数功能：初始化日志链（验明正身 → 检查头扇区 → 扫描写指针）
 * 返回值  ：APP_LOGGER_OK = 就绪；APP_LOGGER_ERR_NO_DEV = 器件不在/型号不符
 * 调用处  ：app_storage_task 开头（内部已打印 JEDEC 与扫描结果）
 * 注意事项：① 失败不影响系统其余功能：调用方自降级（本例：周期追加被跳过）
 *           ② 扫描说明（与课件一致的简化约定）：
 *              - 全新芯片（全 0xFF）→ 从头开始记；
 *              - 中途断电重启      → 扫到第一个空位接着写，seq 接着涨；
 *              - 8 MB 整体写满后   → 环形重启：回到 0 号扇区重擦重写
 *                （教学工程简化：每写满一圈，历史从 0 重新计）
 *----------------------------------------------------------------------------*/
int APP_LOGGER_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：周期动作：取 DHT11 快照 → 追加一条 → 读回比对 → 串口打一行
 * 调用处  ：app_storage_task 每 APP_LOGGER_PERIOD_MS 一拍
 * 注意事项：DHT11 还没采到有效数据（valid=0）时跳过本拍，不记空数据
 *----------------------------------------------------------------------------*/
void APP_LOGGER_Periodic(void);

/*----------------------------------------------------------------------------
 * 函数功能：追加一条记录（含"位置不空 → 整扇区重擦"的先擦后写决策）
 * 返回值  ：APP_LOGGER_OK / ERR_IO / ERR_VERIFY
 *----------------------------------------------------------------------------*/
int APP_LOGGER_Append(uint32_t tick_s, int16_t temp_x10, uint16_t humi_x10);

/*----------------------------------------------------------------------------
 * 函数功能：按序号读一条（index=0 最新一条，1 次新，…）
 * 返回值  ：APP_LOGGER_OK / ERR_PARAM / ERR_IO
 *----------------------------------------------------------------------------*/
int APP_LOGGER_Read(uint32_t index, app_log_rec_t *out);

/* 当前有效记录数（首次写满前 = 已写条数；环形重启后从 0 重计） */
uint32_t APP_LOGGER_Count(void);
#endif /* APP_LOGGER_ENABLE */

#endif /* APP_LOGGER_H */
