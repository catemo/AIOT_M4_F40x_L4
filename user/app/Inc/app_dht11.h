/**
 ******************************************************************************
 * @file    app_dht11.h
 * @brief   应用层（app）—— DHT11 温湿度周期采集任务接口
 *
 *  本层是 DHT11 链的"业务侧"：决定多久读一次、读失败怎么办、读到了怎么用。
 *  与之对应的感知层 per_dht11 只管"40 个脉宽怎么变成 4 个字节"。
 *
 *  任务主循环每 2 秒做四件事（见 P26 流程图）：
 *    ① 读：per_dht11 读一次，失败最多重试 3 次
 *    ② 用：成功 → 交给 app_link 做阈值联动
 *    ③ 报：把 Temp / Hum 或失败 stage 从串口打出去
 *    ④ 歇：osDelay(2000) 把 CPU 让给别的任务
 *
 *  ★ 故障安全的落点在③：
 *    读失败时【不调用】app_link —— 没有输入就没有动作，
 *    两颗灯保持上一次的状态，绝不因为"读不到数"就乱闪一通。
 *    这条设计让"传感器没接"和"联动逻辑错了"在现象上完全不同，好排查。
 *
 *  ★ 打印为什么走 MOD_UART1_SendString 而不是 printf：
 *    本工程刻意不引入 printf 格式化库（会拉进几 KB 的 FLASH）。
 *    本册自己拼字符串，代价是几十行、收益是不占那几 KB ——
 *    对一个 512 KB FLASH 的教学工程来说，省下来的是"还能再加一个模块"的余量。
 ******************************************************************************
 */
#ifndef APP_DHT11_H
#define APP_DHT11_H

#include <stdint.h>

/*----------------------------------------------------------------------------
 * 函数功能：DHT11 温湿度采集任务体（永不返回）
 * 参数    ：argument —— CMSIS-RTOS2 要求的任务参数槽（本任务不使用，恒为 NULL）
 * 返回值  ：无（任务体不返回；万一返回，FreeRTOS 会当作异常）
 * 调用处  ：app_task.c 的 app_taskCreate() 里被 osThreadNew 登记，
 *          调度器启动（osKernelStart）后由内核调用
 * 注意事项：① ★ 传函数名而不是调用它：osThreadNew(app_dht11_task, ...)，
 *              写成 app_dht11_task(...) 就是"当场调用"，任务永远不会建立
 *           ② 本任务内部有三段"必须连续占用 CPU"的时间：
 *              起始信号 18 ms 忙等、40 位读取约 4~5 ms 关中断、自检约 25 ms。
 *              其余时间一律用 osDelay 让出 CPU，不忙等
 *           ③ 优先级与 LED 任务、串口任务同为 1（平级）：
 *              三者按时间片轮转，谁 osDelay 谁让出，互不抢占
 *----------------------------------------------------------------------------*/
void app_dht11_task(void *argument);

/* ===================== 最近一次采集的快照 =====================
 * ★ 为什么要这个结构：上云任务每 5 秒上报一次，而采集任务每 2 秒读一次
 *   （DHT11 最快 1 Hz，不能为了上报去催它）。最省事、也最省资源的做法是
 *   采集任务把"最近一组读数"放在这里，上报任务只读不算——
 *   采集慢、上传快（或反过来）时，两边都不互相拖累。
 * ★ 一写一读、都是 32 位对齐读写，不加锁也不会读到半截：
 *   写方（采集任务）在 seq 上加一，读方可以靠 seq 判断"这期间有没有更新"。
 *   ★ 这是本工程"快照"与"队列"之间刻意选前者的地方：
 *     上报要的是最新值，不是历次值；补历史是 16 条离线缓存干的活。 */
typedef struct
{
    uint8_t  valid;      /* 1 = 至少成功采集过一次（0 时上报会填 0 并标注无效） */
    uint8_t  temp_int;   /* 温度整数部分（℃）   */
    uint8_t  temp_dec;   /* 温度小数部分        */
    uint8_t  humi_int;   /* 湿度整数部分（%RH） */
    uint8_t  humi_dec;   /* 湿度小数部分        */
    uint32_t seq;        /* 更新序号：每成功采集一次 +1                  */
} APP_DHT11_Snapshot_t;

/*----------------------------------------------------------------------------
 * 函数功能：取最近一次采集的快照（只读，不会触发新的采集）
 * 参数    ：out —— 输出结构（NULL 时直接返回）
 * 返回值  ：无
 * 调用处  ：app_mqtt.c 的周期上报
 * 注意事项：① 本函数【不阻塞、不发指令、不碰引脚】：它只做一次结构体拷贝，
 *              所以上云任务每 50ms 调一次也没有成本
 *           ② out->valid = 0 表示还没采到过有效数据（刚上电的那几秒），
 *              上报方应当如实说明"数据未就绪"，而不是编一个 0
 *----------------------------------------------------------------------------*/
void APP_DHT11_GetSnapshot(APP_DHT11_Snapshot_t *out);

#endif /* APP_DHT11_H */
