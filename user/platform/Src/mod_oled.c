/* ========== 内部：一帧命令 / 一帧数据 ========== */

static void oled_write_cmd(uint8_t cmd)
{
    NET_I2CSW_Start();
    NET_I2CSW_WriteByte(MOD_OLED_I2C_ADDR_WRITE);
    NET_I2CSW_WriteByte(0x00U);   /* Co = 0, D/C# = 0 → 后续字节是命令 */
    NET_I2CSW_WriteByte(cmd);
    NET_I2CSW_Stop();
}

static void oled_write_data(uint8_t data)
{
    NET_I2CSW_Start();
    NET_I2CSW_WriteByte(MOD_OLED_I2C_ADDR_WRITE);
    NET_I2CSW_WriteByte(0x40U);   /* Co = 0, D/C# = 1 → 后续字节是显存数据 */
    NET_I2CSW_WriteByte(data);
    NET_I2CSW_Stop();
}

