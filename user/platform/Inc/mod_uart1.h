/**
 ******************************************************************************
 * @file    mod_uart1.h
 * @brief   平台层（platform）—— 串口1 统一入口（1 个 UART：收 / 发字节）
 *
 *  本层职责：给上层一套"与硬件无关、与协议无关"的名字（MOD_UART1_*），
 *  把网络层的函数名、huart1 句柄、DMA 判帧细节全部挡在后面。
 *
 *  ★ 关键规矩：上层（app_cmd.c）只许 include 本文件，
 *    永远不许 include net_uart.h —— 这就是"统一入口"存在的意义。
 *
 *  为什么串口链要三层（app → platform → network）而 LED 链只有两层
 *  （app → perception）？这不是多此一举：
 *    - network 管【字节】：怎么收上来、怎么发出去（DMA / 中断 / 缓冲）
 *    - platform 管【入口】：对上层只暴露"这一个串口"的读写名字，
 *      也是将来承载协议与 MQTT 的地方（本册它只做薄转发，K05 章节才长肉）
 *    - app 管【语义】：一行字符串到底要灯做什么
 *  三层各管一段，换串口号（USART1 → USART2）、换传输方式（串口 → MQTT）时，
 *  上层代码一行都不用改。
 *
 *  硬件对应：USART1，PA9 = TX，PA10 = RX，115200-8-N-1
 ******************************************************************************
 */
#ifndef MOD_UART1_H
#define MOD_UART1_H

#include <stdint.h>

/*----------------------------------------------------------------------------
 * 函数功能：启动 UART1 接收链路（转发 net_uart_init：DMA 循环 + IDLE 中断）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：app_cmd.c 的 app_cmd_task()，任务入口处调一次
 * 注意事项：① USART1 / DMA 本体在 main() 里已由 CubeMX 代码完成初始化，
 *              这里只是把"收数据"拉起来
 *           ② 本层不加工任何返回值：网络层内部已消化了"启动失败重试"，
 *              上层不需要为基础设施写错误处理分支
 *----------------------------------------------------------------------------*/
void MOD_UART1_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：查询接收缓冲里有多少字节可读
 * 参数    ：无
 * 返回值  ：可读字节数（0 = 暂时没收到）
 * 调用处  ：app_cmd.c 的 app_cmd_task()（判断是否值得去读）
 *----------------------------------------------------------------------------*/
uint32_t MOD_UART1_Available(void);

/*----------------------------------------------------------------------------
 * 函数功能：从接收缓冲读出数据（任务侧消费）
 * 参数    ：buf —— 调用者提供的缓冲区；len —— 期望读取的字节数
 * 返回值  ：实际读到的字节数（缓冲空时返回 0，从不阻塞）
 * 调用处  ：app_cmd.c 的 app_cmd_task()
 * 注意事项：不阻塞、不等待：有多少拿多少，任务循环自己决定下一圈再来
 *----------------------------------------------------------------------------*/
uint32_t MOD_UART1_Read(uint8_t *buf, uint32_t len);

/*----------------------------------------------------------------------------
 * 函数功能：发送一段数据
 * 参数    ：buf —— 待发送数据；len —— 字节数
 * 返回值  ：无
 * 调用处  ：app_cmd.c 的 cmd_exec()（回 OK / ERR / STATUS）
 * 注意事项：只能在本层的下游是"阻塞发送"时用于短数据；
 *           本册回的都是几十字节的短句，占用 CPU 在几十微秒量级
 *----------------------------------------------------------------------------*/
void MOD_UART1_Send(const uint8_t *buf, uint32_t len);

/*----------------------------------------------------------------------------
 * 函数功能：发送一个以 '\0' 结尾的字符串
 * 参数    ：str —— 待发送字符串
 * 返回值  ：无
 * 调用处  ：app_cmd.c 的 cmd_exec() / 启动打招呼
 *----------------------------------------------------------------------------*/
void MOD_UART1_SendString(const char *str);

#endif /* MOD_UART1_H */
