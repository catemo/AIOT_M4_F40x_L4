/**
 ******************************************************************************
 * @file    mod_oled.h
 * @brief   平台层（platform）—— SSD1306 OLED 器件驱动接口（2.9 新增）
 *
 *  器件知识都在这两层文件里，本层往下只依赖网络层的软件 I2C 总线
 *  （net_i2c_sw），往上只暴露"页 / 列 / 字符串"这种显示语义。
 *
 *  0.96" SSD1306 摘要：
 *    - 分辨率 128×64 单色，显存 GDDRAM 1 KB，按【页】组织：8 页 × 128 列，
 *      每列 1 字节 = 纵向 8 个像素（bit0 在上、bit7 在下）
 *    - I2C 地址 0x3C（SA0 = 0），写地址 = 0x3C << 1 = 0x78
 *      （不同厂家可能是 0x3D / 写 0x7A：屏不亮时先换地址试）
 *    - I2C 每帧 = 从机地址 + 控制字节 + 载荷：
 *        0x00 → 后面是【命令】   0x40 → 后面是【显存数据】
 *    - 3.3 V 供电，像素需要 7~15 V 驱动，靠内部电荷泵升压（0x8D/0x14）
 *
 *  字库：
 *    - 6x8  小字体：每字符 6 列 × 1 页，每行 21 字符，共 8 行
 *    - 8x16 大字体：每字符 8 列 × 2 页，每行 16 字符，共 4 行
 *      （★ 不手写 8x16 字模表：从已验证的 6x8 实时放大——
 *        纵向每像素复制 2 次、横向左右各补 1 列空白，字模正确性天然有保证）
 ******************************************************************************
 */
#ifndef MOD_OLED_H
#define MOD_OLED_H

#include <stdint.h>

/* ========== 器件地址与显示参数 ========== */
#define MOD_OLED_I2C_ADDR       0x3CU   /* 7 位地址（SA0 = 0） */
#define MOD_OLED_I2C_ADDR_WRITE 0x78U   /* 写地址 = 0x3C << 1 */
#define MOD_OLED_WIDTH          128U
#define MOD_OLED_HEIGHT         64U
#define MOD_OLED_PAGES          8U      /* 64 / 8 = 8 页 */

#define MOD_OLED_FONT6_WIDTH    6U      /* 6x8 小字体：字符宽 6 列 */
#define MOD_OLED_FONT8_WIDTH    8U      /* 8x16 大字体：字符宽 8 列 */

/*----------------------------------------------------------------------------
 * 函数功能：OLED 初始化（SSD1306 上电初始化序列 + 清屏）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：应用层 app_oled.c 的 APP_OLED_Init()（调度器启动前）
 * 注意事项：① ★ 序列里两条是"屏亮不亮"的生死线：
 *              电荷泵使能 0x8D/0x14（不使能 → 像素没有驱动电压 → 永久全黑），
 *              显示开 0xAF（漏发 → 显存写得再对也不亮）
 *           ② 0xC8 + 0xA1 是扫描方向映射：不同厂家模块装反了字会上下颠倒
 *              或左右镜像，换屏后这两条最可能要调
 *           ③ 初始化期间先 0xAE 关显示，配完再 0xAF 开——避免把中间态闪给用户
 *           ④ 本函数会调用 HAL_Delay(100) 等电荷泵稳定：HAL 时基是 TIM6 中断，
 *              调度器启动前照常工作，所以放在 app_taskCreate() 里是安全的
 *----------------------------------------------------------------------------*/
void MOD_OLED_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：全屏填充（0xFF = 全亮、0x00 = 全灭），用于上电硬件自检
 * 参数    ：data —— 填充字节
 * 返回值  ：无
 * 调用处  ：app_oled.c 的自检（点亮 500 ms → 清屏）
 * 注意事项：全屏点亮一次自检三件事：I2C 通、供电足、像素全好
 *----------------------------------------------------------------------------*/
void MOD_OLED_Fill(uint8_t data);

/*----------------------------------------------------------------------------
 * 函数功能：清屏（逐页逐列写 0x00）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：初始化末尾、自检之后
 * 注意事项：整屏 8×128 = 1024 字节，每条数据一帧 I2C 事务，
 *           115200 波特率下约几十毫秒——只在初始化与自检时用，业务刷新不调它
 *----------------------------------------------------------------------------*/
void MOD_OLED_Clear(void);

/*----------------------------------------------------------------------------
 * 函数功能：设置光标（页寻址模式：页号 0~7 + 列号 0~127）
 * 参数    ：page —— 页号；col —— 列号（越界自动夹到边界）
 * 返回值  ：无
 * 调用处  ：本文件的 ShowChar / ShowChar8x16
 * 注意事项：页寻址模式下，写数据时列地址会自动 +1、到 127 后回卷到 0，
 *           但【页号不会自动加】——所以整屏操作必须外层再套一层页循环
 *----------------------------------------------------------------------------*/
void MOD_OLED_SetCursor(uint8_t page, uint8_t col);

/*----------------------------------------------------------------------------
 * 函数功能：在指定位置显示一个 ASCII 字符（6x8，占 1 页）
 * 参数    ：page —— 页号 0~7；col —— 列号；ch —— ASCII（0x20~0x7E）
 * 返回值  ：无
 * 调用处  ：MOD_OLED_ShowString
 * 注意事项：不可打印字符按空格显示，不报错也不留白洞
 *----------------------------------------------------------------------------*/
void MOD_OLED_ShowChar(uint8_t page, uint8_t col, char ch);

/*----------------------------------------------------------------------------
 * 函数功能：显示字符串（6x8，自左向右自动排列，越界停止）
 * 参数    ：page —— 页号；col —— 起始列；str —— 以 '\0' 结尾
 * 返回值  ：无
 * 调用处  ：调试或短信息显示（本册主界面用 8x16 大字）
 *----------------------------------------------------------------------------*/
void MOD_OLED_ShowString(uint8_t page, uint8_t col, const char *str);

/*----------------------------------------------------------------------------
 * 函数功能：显示一个 ASCII 字符（8x16，跨 page 与 page+1 两页）
 * 参数    ：page —— 起始页号（0/2/4/6）；col —— 列号（按 8 列步进）
 * 返回值  ：无
 * 调用处  ：MOD_OLED_ShowString8x16
 * 注意事项：字模由 6x8 实时放大：上半页取源字节低 4 位、下半页取高 4 位，
 *           每位横向复制成 2 位（纵向 8→16），左右各补 1 列空白（6→8）
 *----------------------------------------------------------------------------*/
void MOD_OLED_ShowChar8x16(uint8_t page, uint8_t col, char ch);

/*----------------------------------------------------------------------------
 * 函数功能：显示字符串（8x16，自左向右自动排列，越界停止）
 * 参数    ：page —— 起始页号 0/2/4/6；col —— 起始列；str —— 以 '\0' 结尾
 * 返回值  ：无
 * 调用处  ：app_oled.c 的四行布局（Temp / Hum / Light / Level）
 * 注意事项：★ 刷新时务必"整行定宽覆盖"（调用方拼好等宽字符串再上屏），
 *           否则数字从 2 位变 1 位时会残留旧字符
 *----------------------------------------------------------------------------*/
void MOD_OLED_ShowString8x16(uint8_t page, uint8_t col, const char *str);

#endif /* MOD_OLED_H */
