/**
 ******************************************************************************
 * @file    mod_flash.h
 * @brief   平台层（platform）—— W25Q64 扩展 Flash 指令集（2.3 外部存储器新增）
 *
 *  这一层的知识是"W25Q 指令集"，而不是"SPI 时序"：
 *    0x06 WREN 解锁 / 0x20 擦扇区 / 0x02 页编程 / 0x03 读回 / 0x9F 验明正身。
 *  总线怎么翻转字节（片选包络、全双工）属于 net_spi，与本层无关。
 *
 *  ★ 三条铁律（对应课件 19 页）：
 *    ① NOR Flash 只能把 1 写成 0 —— 不擦就写，数据是"与运算"后的残渣；
 *    ② BUSY 轮询期间让出 CPU（osDelay 1 ms），45 ms 的擦除不当死循环；
 *    ③ 不信任单点成功：WEL 要回读确认，写完要读回比对。
 ******************************************************************************
 */
#ifndef MOD_FLASH_H
#define MOD_FLASH_H

#include <stdint.h>

/* W25Q 指令集（单线命令：不依赖 QE 位，兼容一切 W25Q 系列） */
#define W25Q64_CMD_WRITE_ENABLE   0x06u  /* WREN：擦写前必须发，发完回读 WEL 确认 */
#define W25Q64_CMD_WRITE_DISABLE  0x04u  /* WRDI */
#define W25Q64_CMD_READ_STATUS    0x05u  /* RDSR：bit0 = BUSY，bit1 = WEL        */
#define W25Q64_CMD_READ_DATA      0x03u  /* READ：指令 + 24 位地址 + 哑读        */
#define W25Q64_CMD_PAGE_PROGRAM   0x02u  /* PP：把 1 写成 0，≤256 B 且绝不跨页   */
#define W25Q64_CMD_SECTOR_ERASE   0x20u  /* SE：4 KB 全变 0xFF，典型 45 ms       */
#define W25Q64_CMD_JEDEC_ID       0x9Fu  /* 读电子签名：EF 40 17 = 华邦 64 Mbit  */

/* 状态寄存器位 */
#define W25Q64_SR_BUSY            0x01u
#define W25Q64_SR_WEL             0x02u

/* JEDEC ID 期望值：EF = 华邦（Winbond），40 17 = SPI 标准 64 Mbit；
 * 末位 0x18 说明焊的是 W25Q128 —— 这是"换芯片没换型号"的第一现场。
 * ★ 2026-10-29 真机实测：本开发板读回 EF 40 18 = W25Q128（16 MB），
 *   所以驱动同时接受 0x17 与 0x18 两档容量（同系列，指令集完全一致） */
#define W25Q64_JEDEC_MANUF        0xEFu
#define W25Q64_JEDEC_MEMTYPE      0x40u
#define W25Q64_JEDEC_CAPACITY     0x17u   /* W25Q64  = 64 Mbit  =  8 MB */
#define W25Q128_JEDEC_CAPACITY    0x18u   /* W25Q128 = 128 Mbit = 16 MB */

/* 返回值：IO / WREN / VERIFY 分开报——排查方向完全不同 */
#define MOD_FLASH_OK           0
#define MOD_FLASH_ERR_PARAM   -1   /* 地址越界 / 跨页 / 空指针 */
#define MOD_FLASH_ERR_IO      -2   /* 总线报错：查 PB3/4/5、PG10 片选、模式 0 */
#define MOD_FLASH_ERR_TIMEOUT -3   /* 忙等待超时：查时钟与供电 */
#define MOD_FLASH_ERR_WREN    -4   /* WEL 没置上：指令被丢弃，查片选包络 */
#define MOD_FLASH_ERR_VERIFY  -5   /* 写读不一致：查擦除时序/降 SPI 时钟复测 */

/*----------------------------------------------------------------------------
 * 函数功能：初始化 = 验明正身（读 JEDEC ID 并与期望值比对）
 * 返回值  ：MOD_FLASH_OK = EF 40 17 全对；MOD_FLASH_ERR_IO = 无应答/型号不符
 * 调用处  ：app_logger 初始化第一步
 *----------------------------------------------------------------------------*/
int mod_flash_init(void);

/*----------------------------------------------------------------------------
 * 函数功能：读 3 字节 JEDEC ID（原始值，供上层打印）
 *----------------------------------------------------------------------------*/
int mod_flash_read_jedec(uint8_t id[3]);

/*----------------------------------------------------------------------------
 * 函数功能：读容量字节（JEDEC 第 3 字节：0x17 = W25Q64，0x18 = W25Q128）
 * 返回值  ：>0 = 容量码；MOD_FLASH_ERR_IO = 读不到（查接线与片选）
 *----------------------------------------------------------------------------*/
int mod_flash_capacity_id(void);

/*----------------------------------------------------------------------------
 * 函数功能：把容量码翻译成人能读的型号名（"W25Q64 / W25Q128 / unknown 0x??"）
 * 返回值  ：静态字符串，不用释放
 * 注意事项：型号知识属于平台层（谁认识芯片谁翻译），应用层不许自己查表
 *----------------------------------------------------------------------------*/
const char *mod_flash_model_name(void);

/*----------------------------------------------------------------------------
 * 函数功能：当前器件总容量（随 JEDEC 容量码变：0x17 = 8 MB，0x18 = 16 MB）
 * 返回值  ：字节数；容量还没读到时按小的算（保守 8 MB）
 * 调用处  ：本层三处越界防护；FDUMP 诊断可打印
 *----------------------------------------------------------------------------*/
uint32_t mod_flash_total_size(void);

/*----------------------------------------------------------------------------
 * 函数功能：读 len 字节（读没有页限制，可以跨页连续读）
 *----------------------------------------------------------------------------*/
int mod_flash_read(uint32_t addr, uint8_t *buf, uint16_t len);

/*----------------------------------------------------------------------------
 * 函数功能：页编程（★ 一次 ≤ 256 B 且绝不跨页，跨页由调用方切分）
 * 注意事项：① 编程前必须 WREN（本函数内部自己发，含 WEL 回读确认）
 *           ② 编程完自动等 BUSY 清零才返回
 *----------------------------------------------------------------------------*/
int mod_flash_page_program(uint32_t addr, const uint8_t *buf, uint16_t len);

/*----------------------------------------------------------------------------
 * 函数功能：擦 4 KB 扇区（含 WREN + WEL 确认 + 忙等待，典型 45 ms）
 *----------------------------------------------------------------------------*/
int mod_flash_sector_erase(uint32_t addr);

/*----------------------------------------------------------------------------
 * 函数功能：查询忙标志（RDSR bit0）
 * 返回值  ：1 = 忙（正在擦/写），0 = 空闲，<0 = 总线错误
 *----------------------------------------------------------------------------*/
int mod_flash_busy(void);

/*----------------------------------------------------------------------------
 * 函数功能：写使能并回读确认（WREN + 校验 WEL 真的置位）
 * ★ 不信任单点成功：WREN 发完不代表 WEL 置上了——片选包络不对时
 *   W25Q 会静默丢弃整条指令，只有回读 WEL 才能发现
 *----------------------------------------------------------------------------*/
int mod_flash_wren(void);

/*----------------------------------------------------------------------------
 * 函数功能：写后读回比对（"写进去的必须能读出来"）
 * 返回值  ：MOD_FLASH_OK / ERR_VERIFY（内容不一致）/ ERR_IO
 *----------------------------------------------------------------------------*/
int mod_flash_verify(uint32_t addr, const uint8_t *buf, uint16_t len);

/*----------------------------------------------------------------------------
 * 函数功能：扇区写入一条龙 = WREN → 擦 → 逐页编程 → 读回比对
 * 参数    ：addr —— 扇区对齐的 4 KB 地址；buf/len —— ≤ 4096
 * 返回值  ：MOD_FLASH_OK / ERR_PARAM / ERR_IO / ERR_TIMEOUT /
 *           ERR_WREN / ERR_VERIFY
 * 调用处  ：app_logger 的"写满擦最旧"整扇区重写
 * 注意事项：这是"先擦后写"的标准动作序列（对应课件 19 页代码块）；
 *           ★ WEL 在每次擦/编程后自动清零，所以每次擦、每页编程前
 *             都要重新 WREN —— 这是与课件简化版（只 WREN 一次）的差异，
 *             也是 W25Q 数据手册的硬性要求
 *----------------------------------------------------------------------------*/
int mod_flash_sector_write(uint32_t addr, const uint8_t *buf, uint16_t len);

#endif /* MOD_FLASH_H */
