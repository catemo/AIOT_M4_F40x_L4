/**
 ******************************************************************************
 * @file    mod_eeprom.h
 * @brief   平台层（platform）—— AT24C02 EEPROM 器件语义（2.3 外部存储器新增）
 *
 *  这一层的知识是"器件"而不是"总线"：
 *    地址是几（0xA0）/ 写周期多长（5 ms）/ 页多大 / 容量多少 / 字地址几位。
 *  上层（app_param）只知道"往 0x0000 写 20 字节配置块"，
 *  页怎么拆、写完怎么等、字地址发几个字节，全部在本层消化 —— 上层无感。
 *
 *  ★ 型号自动识别（2026-10-29 真机踩坑后加）：
 *    板上焊的可能是 AT24C02（字地址 1 字节、页 8 B）也可能是
 *    AT24C256（字地址 2 字节、页 64 B，参考工程 big_F407ZE_v3.x 就是它）。
 *    两者【器件地址都是 0xA0】，probe 分辨不出来；
 *    init 里按"牺牲地址写 0xA5 再读回"判字地址位宽，自动选定型号参数。
 *    ★ 位宽搞错的现象极具迷惑性：地址帧照样 ACK、写照样返回成功，
 *      但数据整体错位，读回来是空白或乱码 —— 只有读回比对能抓到。
 *
 *  ★ 两条器件铁律（对应课件 17 页）：
 *    ① 页写不能跨页：写地址越过页边界会在页内回绕，把本页开头的数据覆盖掉
 *       —— 驱动按"本页还能写多少"自动切分（页宽随型号变）；
 *    ② 写周期内器件不应答：轮询探 ACK 探到即是写完，比死等 5 ms 更快也更可靠。
 ******************************************************************************
 */
#ifndef MOD_EEPROM_H
#define MOD_EEPROM_H

#include <stdint.h>

/* 器件地址（A2/A1/A0 全接地 → 0xA0；写 0xA0 / 读 0xA1 由 HAL 内部处理）
 * ★ 注意：AT24C256 也用 0xA0（A2/A1 接地时），所以【地址一样、型号不同】
 *   —— 光靠 probe 分辨不出器件型号，必须再探一次"字地址位宽" */
#define AT24C02_ADDR        0xA0u

/* 探测到的器件型号（mod_eeprom_init 里自动识别，上层不必关心） */
typedef enum {
    MOD_EEPROM_CHIP_AT24C02  = 1,   /* ≤2 Kbit：字地址 1 字节，页   8 B，容量   256 B */
    MOD_EEPROM_CHIP_AT24C256 = 2    /* 256 Kbit：字地址 2 字节，页 64 B，容量 32 KB  */
} mod_eeprom_chip_t;

/*----------------------------------------------------------------------------
 * 函数功能：取当前探测到的器件型号
 * 返回值  ：MOD_EEPROM_CHIP_AT24C02 / AT24C256
 * 调用处  ：串口 PDUMP / ISCAN 诊断打印
 *----------------------------------------------------------------------------*/
mod_eeprom_chip_t mod_eeprom_chip(void);

/*----------------------------------------------------------------------------
 * 函数功能：型号名（"AT24C02" / "AT24C256"，打印用）
 *----------------------------------------------------------------------------*/
const char *mod_eeprom_chip_name(void);

/*----------------------------------------------------------------------------
 * 函数功能：当前器件的页大小 / 总容量（随型号变化，别在别处写死 8 和 256）
 *----------------------------------------------------------------------------*/
uint16_t mod_eeprom_page_size(void);
uint32_t mod_eeprom_total_size(void);

/* 返回值：IO / TIMEOUT / VERIFY 分开报——
 *   IO      = 没接好（查硬件）
 *   TIMEOUT = 没写完（查时序与供电）
 *   VERIFY  = 写进去了但读回来对不上（查页拆分/写周期/兼容片） */
#define MOD_EEPROM_OK          0
#define MOD_EEPROM_ERR_PARAM  -1   /* 地址越界或空指针 */
#define MOD_EEPROM_ERR_IO     -2   /* 总线报错：查接线/上拉/地址脚 */
#define MOD_EEPROM_ERR_TIMEOUT -3  /* 写周期轮询超时：查供电与器件好坏 */
#define MOD_EEPROM_ERR_VERIFY -4   /* 逐页读回对不上：查页拆分与写周期等待 */

/*----------------------------------------------------------------------------
 * 函数功能：初始化 = 总线健康检查 + 器件探测
 * 返回值  ：MOD_EEPROM_OK = 器件应答正常；MOD_EEPROM_ERR_IO = 总线或器件不通
 * 调用处  ：app_param 的加载流程第一步
 * 注意事项：幂等，重复调用无副作用；器件不在时返回错误但不影响系统其余功能
 *----------------------------------------------------------------------------*/
int mod_eeprom_init(void);

/*----------------------------------------------------------------------------
 * 函数功能：只发地址帧探应答（透传 net_i2c_probe 的结果语义）
 * 返回值  ：MOD_EEPROM_OK = 有 ACK；MOD_EEPROM_ERR_IO = 无应答/总线故障
 *----------------------------------------------------------------------------*/
int mod_eeprom_probe(void);

/*----------------------------------------------------------------------------
 * 函数功能：探【任意】8 位器件地址（ISCAN 诊断命令用它扫总线）
 * 参数    ：dev —— 8 位写地址（0xA0 / 0xA2 / 0xA4 ... 由 A2/A1/A0 决定）
 * 返回值  ：MOD_EEPROM_OK = 该地址有器件应答；MOD_EEPROM_ERR_IO = 无应答
 * 调用处  ：串口 ISCAN 命令（应用层不直接 include net_i2c，靠本接口守分层）
 * 注意事项：只发地址帧，不读不写，对器件无副作用 —— 可以放心全表扫一遍
 *----------------------------------------------------------------------------*/
int mod_eeprom_probe_dev(uint8_t dev);

/*----------------------------------------------------------------------------
 * 函数功能：读 len 字节（读没有写周期，也没有页回绕问题，一包到底）
 * 参数    ：addr —— 器件内字地址（0~255）；buf/len —— 输出
 * 返回值  ：MOD_EEPROM_OK / ERR_PARAM / ERR_IO
 *----------------------------------------------------------------------------*/
int mod_eeprom_read(uint16_t addr, uint8_t *buf, uint16_t len);

/*----------------------------------------------------------------------------
 * 函数功能：写 len 字节（★ 页写自动拆分 + 每页写后轮询 ACK）
 * 参数    ：addr —— 器件内字地址（0~255）；buf/len —— 输入
 * 返回值  ：MOD_EEPROM_OK / ERR_PARAM / ERR_IO / ERR_TIMEOUT
 * 调用处  ：app_param（写配置块、写回重启计数）
 * 注意事项：① 容量先卡死：addr + len 越过 256 直接拒绝，不让非法访问穿透
 *           ② 20 字节配置块从 0x0000 写 = 3 页（8+8+4）≈ 15 ms —— 写参数是
 *              重操作，"变了才写"的纪律在应用层守
 *----------------------------------------------------------------------------*/
int mod_eeprom_write(uint16_t addr, const uint8_t *buf, uint16_t len);

#endif /* MOD_EEPROM_H */
