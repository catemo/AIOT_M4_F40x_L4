/**
 ******************************************************************************
 * @file    mod_wifi.h
 * @brief   平台层（platform）—— WiFi 统一入口：五个语义动作
 *
 *  本层把"AT 指令"翻译成"人话"，上层（mod_mqtt / app_mqtt）从此看不到
 *  AT 三个字母，也看不到 CIPSTART、WIFI GOT IP 这些词。
 *
 *  ★ 边界画在这里：
 *      这层之上：只有"连网、建链、收发"这四件事
 *      这层之下：AT 指令、关键字、超时、+IPD、两条缓冲
 *    换 4G / CAT1 模组 → 只重写本层与 net_xxx，mod_mqtt 与 app_mqtt 一行不改。
 *
 *  ★ 与 mod_uart1 是同一个思想：
 *    上层永远不该出现"这条指令要等哪个关键字"这种细节——
 *    就像 app_cmd 不需要知道 DMA 怎么配。区别只是：mod_uart1 是"薄转发"，
 *    而本层有真正的知识（状态映射、失败归类），所以它必须单独成层。
 *
 *  ★ 失败不在本层重试：
 *    Send 失败就返回失败，重连由 app_mqtt 的退避策略决定。
 *    分层里"谁懂全局，谁做决策"——本层不知道现在是第几次重连，
 *    也不知道离线缓存里还有几条数据，凭什么决定要不要重试。
 ******************************************************************************
 */
#ifndef MOD_WIFI_H
#define MOD_WIFI_H

#include <stdint.h>

/* ===================== 状态码（把网络层的细分错误归成上层看得懂的几类） ====
 * ★ 为什么不用 bool：上面需要"是超时还是模块拒绝"这两种不同的失败——
 *   超时要退避更久，模块拒绝（FAIL/ERROR）要复位模块。归成一类就丢了信息。 */
typedef enum
{
    MOD_WIFI_OK = 0,       /* 动作成功 */
    MOD_WIFI_ERR_TIMEOUT,  /* 等不到响应：多半是模块没接好 / 供电不足 */
    MOD_WIFI_ERR_FAIL,     /* 模块明确回了 ERROR / FAIL：指令被拒绝 */
    MOD_WIFI_ERR_CLOSED,   /* TCP 已被对端关闭 */
    MOD_WIFI_ERR_PARAM     /* 参数非法（空指针） */
} MOD_WIFI_Status_t;

/*----------------------------------------------------------------------------
 * 函数功能：初始化 WiFi 通道（拉起 USART3 + 等模块上电稳定）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：app_mqtt.c 的 app_mqtt_task() 启动序列第一步
 * 注意事项：本函数不连网、不发 AT，只做"让模块能被对话"的准备；
 *           真正的连接是下面那几个动作，分段做、失败可只重做某一段
 *----------------------------------------------------------------------------*/
void MOD_WIFI_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：AT 测活
 * 参数    ：无
 * 返回值  ：MOD_WIFI_OK / ERR_TIMEOUT / ERR_FAIL
 * 调用处  ：app_mqtt 的连接状态机第 ① 段
 * 注意事项：这是整条链的"第一现场"：它不通，后面全部不用试
 *----------------------------------------------------------------------------*/
MOD_WIFI_Status_t MOD_WIFI_TestAt(void);

/*----------------------------------------------------------------------------
 * 函数功能：切 Station 模式（去连路由器）
 * 参数    ：无
 * 返回值  ：状态码
 * 调用处  ：app_mqtt 的连接状态机第 ② 段
 *----------------------------------------------------------------------------*/
MOD_WIFI_Status_t MOD_WIFI_SetSta(void);

/*----------------------------------------------------------------------------
 * 函数功能：连接路由器
 * 参数    ：ssid / pwd —— WiFi 名称与密码
 * 返回值  ：状态码（成功 = 模块拿到 IP）
 * 调用处  ：app_mqtt 的连接状态机第 ③ 段
 * 注意事项：最长阻塞 10 秒（DHCP），期间用 osDelay 让出 CPU：灯照常闪
 *----------------------------------------------------------------------------*/
MOD_WIFI_Status_t MOD_WIFI_JoinAp(const char *ssid, const char *pwd);

/*----------------------------------------------------------------------------
 * 函数功能：建 TCP 连接（成功后自动切到 MQTT 二进制接收模式）
 * 参数    ：host —— 域名或 IP；port —— 端口
 * 返回值  ：状态码
 * 调用处  ：app_mqtt 的连接状态机第 ④ 段
 * 注意事项：★ "建链成功就切 MQTT 模式"这一步刻意放在本函数里，而不是让
 *           上层记得去切——上层忘了切，现象是 "CONNACK 永远等不到"，
 *           而这恰恰是最难查的一类故障
 *----------------------------------------------------------------------------*/
MOD_WIFI_Status_t MOD_WIFI_OpenTcp(const char *host, uint16_t port);

/*----------------------------------------------------------------------------
 * 函数功能：发送一段数据（内部走 CIPSEND 四步）
 * 参数    ：buf —— 待发送字节；len —— 长度
 * 返回值  ：状态码
 * 调用处  ：mod_mqtt.c 的所有发送路径
 * 注意事项：① 二进制安全：MQTT 报文里有 0x00，所以必须传长度、不能靠 '\0'
 *           ② 失败不重试：重试与退避是应用层的事
 *----------------------------------------------------------------------------*/
MOD_WIFI_Status_t MOD_WIFI_Send(const uint8_t *buf, uint16_t len);

/*----------------------------------------------------------------------------
 * 函数功能：接收数据（从 +IPD 分流出来的载荷缓冲里取）
 * 参数    ：buf —— 接收缓冲；max —— 期望字节数
 * 返回值  ：实际读到的字节数（0 = 这段时间没数据，不代表断线）
 * 调用处  ：mod_mqtt.c 的收包路径
 * 注意事项：内部最多等 10ms 就走，交给调用者决定要不要再来一次——
 *           这样主循环的节拍不会被一个"永远等不到的数据"卡住
 *----------------------------------------------------------------------------*/
uint16_t MOD_WIFI_Recv(uint8_t *buf, uint16_t max);

/*----------------------------------------------------------------------------
 * 函数功能：关闭 TCP（并置"已断开"标志）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：app_mqtt 在 CONNECT 失败 / 半开连接时强制重建
 * 注意事项：★ 半开连接（TCP 还在、MQTT 已经死了）的处理办法就是它：
 *           别在旧连接上死磕，关掉重建，代价只有一次 CIPSTART
 *----------------------------------------------------------------------------*/
void MOD_WIFI_Close(void);

/*----------------------------------------------------------------------------
 * 函数功能：硬复位模块（AT+RST）
 * 参数    ：无
 * 返回值  ：状态码
 * 调用处  ：app_mqtt 连续 5 次重连失败后的"最后一招"
 * 注意事项：复位会清掉所有连接状态，包括 MQTT 模式标志——复位后要重新建链
 *----------------------------------------------------------------------------*/
MOD_WIFI_Status_t MOD_WIFI_Reset(void);

/*----------------------------------------------------------------------------
 * 函数功能：TCP 是否已断开（纯内存标志，不发 AT）
 * 参数    ：无
 * 返回值  ：1 = 已断开
 * 调用处  ：mod_mqtt 的收包路径（读不到数据时用它区分"没数据"与"断了"）
 *----------------------------------------------------------------------------*/
uint8_t MOD_WIFI_IsTcpClosed(void);

/*----------------------------------------------------------------------------
 * 函数功能：取上一次 AT 操作的原始响应（排障）
 * 参数    ：buf —— 缓冲；cap —— 容量
 * 返回值  ：拷贝的字节数
 * 调用处  ：app_mqtt 在连接失败时打印"现场"
 * 注意事项：本层只把现场递上去，不自己打印——打印是应用层的事
 *----------------------------------------------------------------------------*/
uint32_t MOD_WIFI_GetLastResp(uint8_t *buf, uint32_t cap);

#endif /* MOD_WIFI_H */
