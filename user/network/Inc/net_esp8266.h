/**
 ******************************************************************************
 * @file    net_esp8266.h
 * @brief   网络层（network）—— ESP8266 AT 会话 + +IPD 二进制分流
 *
 *  本层在四层架构里的位置：
 *      app_mqtt       报什么 / 多久报 / 命令怎么响应
 *      mod_mqtt       MQTT 报文编解码
 *      mod_wifi       五个语义动作（连 AP / 建 TCP / 收发）
 *    → net_esp8266    本层：AT 这门"文本协议"的收发与分流
 *      net_uart       USART3 实例的字节流（DMA + IDLE + 环形缓冲）
 *
 *  ★ 本层独有的知识只有两件，但两件都绕不开：
 *    ① 一条 AT 会话的三步：发指令（自动补 \r\n）→ 等关键字 → 超时 dump
 *       "等关键字"才是 AT 的本质：模块不是按字节回，是按【文本行】回，
 *       所以判断成功的依据是"响应里出现了 OK 这个子串"，不是"收到了几个字节"。
 *    ② +IPD 分流：USART3 上永远混着两种东西 —— AT 文本响应与 MQTT 二进制载荷。
 *       前者可以按行切、可以丢；后者一位都不能改，必须原样搬进独立缓冲。
 *       这就是本层要维护【两条缓冲】的全部原因。
 *
 *  ★ 为什么 AT 三个字母不许出现在平台层以上：
 *    换模组（ESP8266 → 4G/CAT1）时只需要重写本层，
 *    mod_wifi 的五个动作、mod_mqtt 的四种报文、app_mqtt 的业务一行不改。
 *
 *  ★ 本层【不打印】：超时的时候它只把原始响应留在内部，
 *    由应用层取出来变成文字。理由与 DHT11 的自检一样——
 *    网络层若去调串口打印，依赖方向就倒过来了（下层调上层）。
 *
 *  硬件对应：USART3，PB10 = TX，PB11 = RX，115200-8-N-1
 ******************************************************************************
 */
#ifndef NET_ESP8266_H
#define NET_ESP8266_H

#include <stdint.h>

/* ===================== 返回码 ===================== */
typedef enum
{
    NET_ESP8266_OK = 0,        /* 收到期望关键字 */
    NET_ESP8266_ERR_TIMEOUT,   /* 等到超时也没等到 */
    NET_ESP8266_ERR_RESPONSE,  /* 收到了 ERROR / FAIL / SEND FAIL */
    NET_ESP8266_ERR_PARAM      /* 参数非法（空指针 / 长度为 0） */
} NET_ESP8266_Status_t;

/*----------------------------------------------------------------------------
 * 函数功能：初始化 ESP8266 通道（拉起 USART3 接收链路 + 等模块上电稳定）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：network/net_esp8266.c 由 mod_wifi 的 MOD_WIFI_Init() 间接触发；
 *           实际调用点在 MOD_WIFI_Init() 内部第一步
 * 注意事项：① 内部会等 2 秒（分片 osDelay），让模块把上电乱码吐完；
 *              这 2 秒里 CPU 是让出去的，LED 任务照常闪
 *           ② 会清空接收链路：上电时的 "ready" 之类信息不参与后续判断
 *           ③ 与 net_uart_init 的关系：本函数只负责"模块侧"的等待，
 *              真正的 DMA 启动在 net_uart_init(NET_UART_WIFI) 里
 *----------------------------------------------------------------------------*/
void net_esp8266_init(void);

/*----------------------------------------------------------------------------
 * 函数功能：发一条 AT 测活（等 OK）
 * 参数    ：timeout_ms —— 超时毫秒数
 * 返回值  ：NET_ESP8266_OK / ERR_TIMEOUT / ERR_RESPONSE
 * 调用处  ：mod_wifi 的 MOD_WIFI_TestAt()
 * 注意事项：这是整条链的"心跳线"：它不通，下面所有动作都没有意义，
 *           所以排障顺序永远是"先看有没有 AT OK"
 *----------------------------------------------------------------------------*/
NET_ESP8266_Status_t net_esp8266_test_at(uint32_t timeout_ms);

/*----------------------------------------------------------------------------
 * 函数功能：切到 Station 模式（AT+CWMODE=1）
 * 参数    ：无
 * 返回值  ：状态码
 * 调用处  ：mod_wifi 的 MOD_WIFI_SetSta()
 * 注意事项：STA 模式 = "去连别人的路由器"；AP 模式是自己当热点。
 *           连华为云必须 STA
 *----------------------------------------------------------------------------*/
NET_ESP8266_Status_t net_esp8266_set_sta(void);

/*----------------------------------------------------------------------------
 * 函数功能：连接路由器（AT+CWJAP="ssid","pwd"）
 * 参数    ：ssid / pwd —— WiFi 名称与密码（都不许为空）
 * 返回值  ：状态码（成功标志是响应里出现 "WIFI GOT IP"，不是 "OK"）
 * 调用处  ：mod_wifi 的 MOD_WIFI_JoinAp()
 * 注意事项：① 成功关键字是 WIFI GOT IP（DHCP 拿到地址），
 *              只看到 OK 还不够——那只是"指令被接受"
 *           ② 超时 10 秒：DHCP 分配地址比普通指令慢一个量级
 *           ③ 路由器必须是 2.4 GHz；ESP8266 不支持 5 GHz，
 *              现象是 CWJAP 一直 FAIL，与密码错一模一样
 *----------------------------------------------------------------------------*/
NET_ESP8266_Status_t net_esp8266_join_ap(const char *ssid, const char *pwd);

/*----------------------------------------------------------------------------
 * 函数功能：建 TCP 连接（AT+CIPMUX=0 → AT+CIPSTART="TCP","host",port）
 * 参数    ：host —— 域名或 IP（模块内部做域名解析）
 *           port —— 端口（华为云明文 MQTT 是 1883）
 * 返回值  ：状态码（成功标志是响应里出现 "CONNECT"）
 * 调用处  ：mod_wifi 的 MOD_WIFI_OpenTcp()
 * 注意事项：① 先 CIPMUX=0 设成单连接：多连接模式下 +IPD 会多一个 link_id 字段，
 *              分流代码与报文长度都要跟着改，本工程刻意用单连接
 *           ② 超时 8 秒：域名解析 + 三次握手，比普通指令慢
 *           ③ 连接成功会清掉"TCP 已断开"标志
 *----------------------------------------------------------------------------*/
NET_ESP8266_Status_t net_esp8266_open_tcp(const char *host, uint16_t port);

/*----------------------------------------------------------------------------
 * 函数功能：发送一段数据（AT+CIPSEND=len → 等 '>' → 发数据 → 等 SEND OK）
 * 参数    ：data —— 待发送字节；len —— 长度
 * 返回值  ：状态码
 * 调用处  ：mod_wifi 的 MOD_WIFI_Send()
 * 注意事项：① 四步一条链路：报长度 → 等 '>' → 发数据 → 等 SEND OK。
 *              少等 '>' 直接发数据，模块会把这堆字节当成 AT 指令解析 → ERROR
 *           ② data 是二进制（MQTT 报文里有 0x00），所以绝不能用 strlen
 *           ③ 失败不在这里重试：重连策略是应用层的事（谁懂全局谁决策）
 *----------------------------------------------------------------------------*/
NET_ESP8266_Status_t net_esp8266_send(const uint8_t *data, uint32_t len);

/*----------------------------------------------------------------------------
 * 函数功能：阻塞读取 TCP 载荷（从 +IPD 分流出来的独立缓冲里取）
 * 参数    ：buf —— 调用者缓冲；len —— 期望字节数；timeout_ms —— 最长等待
 * 返回值  ：实际读到的字节数（0 = 超时无数据；此时要另查 is_tcp_closed）
 * 调用处  ：mod_wifi 的 MOD_WIFI_Recv()
 * 注意事项：① 只在进入 MQTT 模式后有效：未进入时 +IPD 仍留在响应缓冲里
 *           ② 读到 0 不代表断线：可能只是这 10ms 内没有数据，
 *              断线要单独看 net_esp8266_is_tcp_closed()
 *           ③ 等待用 osDelay：让出 CPU，LED 任务与串口命令不受影响
 *----------------------------------------------------------------------------*/
uint32_t net_esp8266_recv(uint8_t *buf, uint32_t len, uint32_t timeout_ms);

/*----------------------------------------------------------------------------
 * 函数功能：关闭 TCP（AT+CIPCLOSE）并置"已断开"标志
 * 参数    ：无
 * 返回值  ：状态码（未连接时模块可能回 ERROR，本函数一律视为已关闭）
 * 调用处  ：mod_wifi 的 MOD_WIFI_Close()
 *----------------------------------------------------------------------------*/
NET_ESP8266_Status_t net_esp8266_close(void);

/*----------------------------------------------------------------------------
 * 函数功能：硬复位模块（AT+RST，等 "ready"）
 * 参数    ：无
 * 返回值  ：状态码
 * 调用处  ：应用层（app_mqtt）在连续多次重连失败后调用
 * 注意事项：这是"最后一招"：模块被半开连接、残留 socket 卡住时，
 *           软的 CIPCLOSE 已经救不回来，只能让它自己重启
 *----------------------------------------------------------------------------*/
NET_ESP8266_Status_t net_esp8266_reset(void);

/*----------------------------------------------------------------------------
 * 函数功能：查询"TCP 是否已断开"（纯内存读，不发任何 AT 指令）
 * 参数    ：无
 * 返回值  ：1 = 已断开（收到独立成行的 CLOSED 或本层主动 Close）；0 = 未断
 * 调用处  ：mod_wifi 的 MOD_WIFI_IsTcpClosed()
 * 注意事项：★ 为什么不用 AT+CIPSTATUS 查：在 MQTT 二进制接收模式下再发 AT，
 *           会把自己收发的报文搅在一起（模块的回显会插进载荷流里）。
 *           所以只在 recv 的字节流里认 "独立成行的 CLOSED"。
 *           为什么不按子串匹配 "CLOSED"：MQTT 报文里也可能碰巧出现这 6 个字节，
 *           按子串匹配会误判成掉线
 *----------------------------------------------------------------------------*/
uint8_t net_esp8266_is_tcp_closed(void);

/*----------------------------------------------------------------------------
 * 函数功能：清掉"TCP 已断开"标志（重连成功后调用）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：mod_wifi 的 MOD_WIFI_OpenTcp() 成功后
 *----------------------------------------------------------------------------*/
void net_esp8266_clear_closed(void);

/*----------------------------------------------------------------------------
 * 函数功能：切到 MQTT 模式（+IPD 里的数据改投独立载荷缓冲，不再留在响应缓冲）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：mod_wifi 的 MOD_WIFI_OpenTcp() 在 TCP 建成后立刻调用
 * 注意事项：★ 必须在 TCP 建连之后、第一帧 MQTT 之前调用。
 *           调用晚了会怎样：CONNACK 那几十个字节被当成 AT 文本留在响应缓冲，
 *           mod_mqtt 永远等不到它 → 表现为"CONNECT 发出去没回应"
 *----------------------------------------------------------------------------*/
void net_esp8266_enter_mqtt_mode(void);

/*----------------------------------------------------------------------------
 * 函数功能：取上一次操作的原始响应（排障用：让应用层把现场打出来）
 * 参数    ：buf —— 调用者缓冲；cap —— 缓冲容量
 * 返回值  ：实际拷贝的字节数（0 = 上一次操作没收到任何字节）
 * 调用处  ：app_mqtt 在连接失败时调用，把原始字节打成 hex + ascii
 * 注意事项：★ 这是"网络层只探测、不打印"的落点：
 *           本层把现场留在内部缓冲里，由上层决定怎么呈现。
 *           读法三条判据：全空 = 接线或供电；有乱码 = 波特率不对；
 *           有内容 = 模块活着，只是这条指令不认
 *----------------------------------------------------------------------------*/
uint32_t net_esp8266_get_last_resp(uint8_t *buf, uint32_t cap);

/*----------------------------------------------------------------------------
 * 函数功能：取走并清掉"载荷缓冲溢出"标志
 * 参数    ：无
 * 返回值  ：1 = 自上次调用以来发生过溢出（丢了最旧的数据）
 * 调用处  ：app_mqtt 主循环（发现溢出时打一行警告）
 * 注意事项：载荷缓冲满了会丢最旧的数据 —— 丢的是数据，所以必须能感知；
 *           与之相对，AT 响应缓冲满了是丢最旧的"状态"文本，无伤大雅
 *----------------------------------------------------------------------------*/
uint8_t net_esp8266_take_overflow(void);

#endif /* NET_ESP8266_H */
