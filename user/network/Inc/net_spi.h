/**
 ******************************************************************************
 * @file    net_spi.h
 * @brief   网络层（network）—— SPI1 总线接口（2.3 外部存储器新增）
 *
 *  与 net_i2c 同一条纪律：只装"总线知识"，不装"器件知识"。
 *  本层不知道 W25Q64 有哪些指令 —— 换 SPI 器件只动平台层。
 *
 *  三个知识点（对应课件 18 页）：
 *    ① 片选是标点符号：一次 transfer = 一个完整片选包络（拉低→交换→拉高），
 *       一条完整指令（含地址与数据）必须待在同一包络里，中途拉高即作废；
 *    ② 全双工交换：发一个字节必收一个字节——发指令/地址时收到的都是垃圾，
 *       读 ID/状态时发出的全是哑字节，TransmitReceive 一步完成；
 *    ③ 忙等待也带超时：标志轮询一律带 NET_SPI_TIMEOUT_MS 上限。
 ******************************************************************************
 */
#ifndef NET_SPI_H
#define NET_SPI_H

#include <stdint.h>

/* 返回值五态：与 net_i2c 同款分诊思路（没接好 / 没发完 / 参数错 分开报） */
#define NET_SPI_OK        0    /* 成功 */
#define NET_SPI_ERR_PARAM -1   /* 参数非法（空指针 / 长度越界） */
#define NET_SPI_BUSY      -2   /* 外设忙，可重试 */
#define NET_SPI_TIMEOUT   -3   /* 交换超时：查时钟极性/相位与接线 */
#define NET_SPI_ERR_IO    -4   /* HAL 报硬错误：查外设状态 */

/*----------------------------------------------------------------------------
 * 函数功能：一次全双工交换 = 一个完整片选包络
 * 参数    ：tx —— 发送缓冲（读操作时放"指令+地址+哑字节"）
 *           rx —— 接收缓冲（写操作时收到的都是垃圾，但必须有地方放）
 *           len —— 交换字节数（tx 与 rx 等长，全双工没有"只发不收"）
 * 返回值  ：NET_SPI_OK / ERR_PARAM / BUSY / TIMEOUT / ERR_IO
 * 调用处  ：mod_flash（W25Q 指令集的每一次收发都走这里）
 * 注意事项：① len 上限 NET_SPI_XFER_MAX（cfg_param.h）：读一页数据最多
 *              4 B 指令头 + 256 B 数据，1024 绰绰有余
 *           ② ★ 片选在本函数内部包络：调用方绝不要自己再拉低/拉高 F_CS，
 *              否则一条指令被切成两半，W25Q 会把它当无效命令丢弃
 *----------------------------------------------------------------------------*/
int net_spi_transfer(const uint8_t *tx, uint8_t *rx, uint16_t len);

#endif /* NET_SPI_H */
