/**
 ******************************************************************************
 * @file    net_i2c.h
 * @brief   网络层（network）—— I2C1 总线接口（2.3 外部存储器新增）
 *
 *  这一层只装"总线知识"，不装任何"器件知识"：
 *    地址帧怎么发 / ACK 怎么等 / 超时怎么退 / 总线卡死怎么救活。
 *  本层不知道 AT24C02 是谁 —— 换成任何 I2C 器件，本层一行不改；
 *  反过来，AT24C02 的页、容量、写周期属于 mod_eeprom，与本层无关。
 *
 *  返回值四态是本层最重要的接口设计（调用方据此区分"没接好"与"没写完"）：
 *    NACK    —— 器件不应答：查器件地址脚（A2/A1/A0）与接线；
 *    TIMEOUT —— 超时：查接线与上拉电阻；
 *    两者分开报，排查方向完全不同（这是 2.3 课件"分诊口诀"的落点）。
 ******************************************************************************
 */
#ifndef NET_I2C_H
#define NET_I2C_H

#include <stdint.h>

/* 返回值四态，调用方据此区分"没接好"与"没写完" */
#define NET_I2C_OK        0    /* 成功 */
#define NET_I2C_BUSY     -1    /* 外设忙，可重试 */
#define NET_I2C_TIMEOUT  -2    /* 超时，查接线与上拉 */
#define NET_I2C_NACK     -3    /* 无应答，探器件：查地址脚与接线 */

/*----------------------------------------------------------------------------
 * 函数功能：初始化 I2C1 总线（检查 SDA/SCL 空闲电平，必要时做九时钟自救）
 * 参数    ：无
 * 返回值  ：NET_I2C_OK = 总线空闲可用；NET_I2C_TIMEOUT = 总线被拉死且救不回来
 * 调用处  ：mod_eeprom_init()（平台层唯一入口，应用层不直接调）
 * 注意事项：① 引脚与外设已在 Core/i2c.c 由 MX_I2C1_Init 配好（main 无条件调用），
 *              本函数只做"总线健康检查 + 按需恢复"，重复调用无副作用
 *           ② 正常空闲 = SDA、SCL 都为高（上拉拉起）；SDA 为低说明有从机
 *              卡住了总线，先自救再报结果
 *----------------------------------------------------------------------------*/
int net_i2c_init(void);

/*----------------------------------------------------------------------------
 * 函数功能：向器件的指定字地址写 len 字节（一次完整 I2C 事务）
 * 参数    ：dev —— 8 位器件地址（写地址，如 0xA0）
 *           mem —— 器件内部的字地址（8 位器件如 AT24C02 取 0~255）
 *           buf —— 数据；len —— 字节数
 * 返回值  ：NET_I2C_OK / BUSY / TIMEOUT / NACK
 * 调用处  ：mod_eeprom（页写循环里逐页调用）
 * 注意事项：① 页边界由平台层负责（8 B 一页），本层只管"这一段字节怎么发"
 *           ② 超时上限来自 cfg_param.h 的 NET_I2C_TIMEOUT_MS，绝不死等
 *           ③ BUSY / TIMEOUT 会先做一次九时钟自救再重试一次；NACK 不重试
 *              ——器件不应答通常是地址/接线问题，重试只是在刷超时
 *----------------------------------------------------------------------------*/
int net_i2c_write(uint8_t dev, uint16_t mem, const uint8_t *buf, uint16_t len);

/*----------------------------------------------------------------------------
 * 函数功能：从器件的指定字地址读 len 字节（一次完整 I2C 事务）
 * 参数    ：同 net_i2c_write
 * 返回值  ：NET_I2C_OK / BUSY / TIMEOUT / NACK
 * 注意事项：读操作没有写周期，失败重试策略与写相同
 *----------------------------------------------------------------------------*/
int net_i2c_read(uint8_t dev, uint16_t mem, uint8_t *buf, uint16_t len);

/*----------------------------------------------------------------------------
 * 函数功能：写 / 读的【带字地址宽度】版本（大容量 EEPROM 专用）
 * 参数    ：mem_16bit —— 0 = 字地址 1 字节（AT24C02 等 ≤2 Kbit 器件）
 *                       非 0 = 字地址 2 字节（AT24C256 等 ≥16 Kbit 器件）
 * 返回值  ：同 net_i2c_write / net_i2c_read
 * 调用处  ：mod_eeprom（由探测到的芯片型号决定传 0 还是 1）
 * 注意事项：★ 这是本层"总线知识"的一部分：I2C 本身不规定字地址几位，
 *           是器件规定；本层只提供"发几个地址字节"的能力，
 *           谁用几位由平台层的器件知识决定 —— 本层仍然不认识 AT24C256。
 *           ★ 字地址位宽搞错的现象极具迷惑性：地址帧照样 ACK、写照样"成功"，
 *           但数据整体错位（AT24C256 会把第一个数据字节当成地址低字节吃掉），
 *           读回来是空白或乱码 —— 只能靠"读回比对"抓到。
 *----------------------------------------------------------------------------*/
int net_i2c_write_ex(uint8_t dev, uint16_t mem, const uint8_t *buf,
                     uint16_t len, uint8_t mem_16bit);
int net_i2c_read_ex(uint8_t dev, uint16_t mem, uint8_t *buf,
                    uint16_t len, uint8_t mem_16bit);

/*----------------------------------------------------------------------------
 * 函数功能：只发地址帧探应答（不写任何数据）
 * 参数    ：dev —— 8 位器件地址
 * 返回值  ：NET_I2C_OK = 有 ACK；NET_I2C_NACK = 无应答；其余同上
 * 调用处  ：mod_eeprom 的两个用途——①上电探测器件在不在 ②写周期轮询
 *           （AT24 写周期内不应答，探到 ACK = 写完了，比死等 5 ms 快且可靠）
 *----------------------------------------------------------------------------*/
int net_i2c_probe(uint8_t dev);

/*----------------------------------------------------------------------------
 * 函数功能：总线卡死自救（F407 名场面）：9 个 SCL 时钟 + 一次 STOP
 * 参数    ：无
 * 返回值  ：NET_I2C_OK = SDA 已释放；NET_I2C_TIMEOUT = 仍被拉死（查供电/地线）
 * 调用处  ：net_i2c 内部（BUSY/TIMEOUT 时自动触发）；也可人工调用
 * 注意事项：① 原理：从机在等"再收一个时钟"把 SDA 松开——主机补发时钟，
 *              从机放掉 SDA，再补一个 STOP 把总线状态机归位
 *           ② 实现路径：把 PB8/PB9 从 AF4 临时切成 GPIO 开漏输出 → 翻转
 *              SCL 九次 → 发 STOP → 切回 AF4 → 重跑 MX_I2C1_Init
 *           ③ 恢复不了（返回 TIMEOUT）说明不是时序卡死，是硬件问题
 *----------------------------------------------------------------------------*/
int net_i2c_recover(void);

#endif /* NET_I2C_H */
