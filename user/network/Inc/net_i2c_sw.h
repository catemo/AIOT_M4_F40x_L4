/**
 ******************************************************************************
 * @file    net_i2c_sw.h
 * @brief   网络层（network）—— 软件 I2C 总线接口（2.9 OLED 新增）
 *
 *  硬件连接（0.96" SSD1306 模块，4 线）：
 *    OLED SCL -> PC4（推挽输出，本层自己配置，上电即高）
 *    OLED SDA -> PC5（推挽输出，本层自己配置，上电即高）
 *    OLED VCC -> 3.3V（模块自带稳压与上拉） / GND -> 与 MCU 共地
 *
 *  为什么不用板上已有的硬件 I2C1（PB8/PB9）：
 *    那一条总线已经给了 AT24C02（参数链），400 kHz 硬件外设的所有权、
 *    超时与卡死自救都写死在 net_i2c.c 里；把 OLED 再挂上去，
 *    等于让"显示"和"掉电保存"互相拖累（一方卡死，另一方跟着黑屏）。
 *    本层用两个 GPIO 手搓 I2C，协议看得见摸得着，时序完全可控，
 *    并且与参数链在物理上一刀两断。
 *
 *  ★ 本层只有"总线知识"：起始/停止/写字节。它不认识 SSD1306，
 *    也不知道 0x78 是什么——器件地址、命令/数据控制字节都在平台层
 *    mod_oled.c。换成 SH1106、换成别的 I2C 屏幕，本层一行不改。
 ******************************************************************************
 */
#ifndef NET_I2C_SW_H
#define NET_I2C_SW_H

#include <stdint.h>

/*----------------------------------------------------------------------------
 * 函数功能：初始化软件 I2C 总线（PC4 = SCL、PC5 = SDA，推挽输出、初始高电平）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：平台层 mod_oled.c 的 MOD_OLED_Init()（应用层不直接调）
 * 注意事项：① ★ 引脚由本函数自己配置（GPIO 时钟 + 推挽 + 无上下拉 + 高速），
 *              没有写进 Core/Src/gpio.c 的 MX_GPIO_Init()：
 *              那两个引脚在本工程 .ioc 里没有登记，CubeMX 重新生成会把
 *              手写内容冲掉；放在驱动里配置，重新生成代码永不丢（与 adc.c 同一条纪律）
 *           ② 上拉电阻在 OLED 模块上（模块自带 4.7k 量级），所以内部 Pull 选 NOPULL；
 *              裸屏必须在 SCL/SDA 与 VCC 之间外接 4.7k~10k，否则永远无应答
 *           ③ 推挽输出 + 不检测 ACK：SSD1306 是这条总线上唯一的从机，
 *              省掉 SDA 方向切换后代码更短，代价是"器件没接也照发不误"——
 *              屏不亮时先量电压/查接线，而不是指望驱动报错
 *           ④ 幂等：重复调用只是把寄存器和电平再写一遍
 *----------------------------------------------------------------------------*/
void NET_I2CSW_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：产生 I2C 起始信号（SCL 高电平期间 SDA 由高变低）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：平台层 mod_oled.c 的每条命令/数据事务开头
 * 注意事项：本层不自带"总线忙"检查：唯一从机 + 单任务互斥（见 app_oled），
 *           两次事务不可能交叠，因此不需要仲裁逻辑
 *----------------------------------------------------------------------------*/
void NET_I2CSW_Start(void);

/*----------------------------------------------------------------------------
 * 函数功能：产生 I2C 停止信号（SCL 高电平期间 SDA 由低变高，释放总线）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：平台层 mod_oled.c 的每条命令/数据事务结尾
 * 注意事项：★ 无论这一帧数据对错，都必须发 STOP：少了它，SSD1306 的 I2C
 *           状态机会停在"等下一个字节"，下一条命令就会错位
 *----------------------------------------------------------------------------*/
void NET_I2CSW_Stop(void);

/*----------------------------------------------------------------------------
 * 函数功能：写一个字节（MSB 在前，共 8 个数据时钟 + 1 个 ACK 时钟）
 * 参数    ：byte —— 待发送字节（器件地址 / 控制字节 / 命令 / 显存数据都走它）
 * 返回值  ：无（不检测 ACK）
 * 调用处  ：平台层 mod_oled.c 的 OLED_WriteCmd() / OLED_WriteData()
 * 注意事项：① ★ 第 9 个时钟必须产生（SCL 拉低 → 释放 SDA → SCL 拉高 → 拉低）：
 *              即使不看应答，SSD1306 也要靠这个时钟确认"这一字节收完了"，
 *              漏掉它，所有命令和数据都不会生效——屏全黑，软件看着却没错
 *           ② 半周期 NET_I2CSW_DELAY_US（默认 2 µs ≈ 250 kHz）：
 *              从机只要求 ≤ 400 kHz，慢一点更稳；花屏时可把它调到 4
 *           ③ SCL 电平翻转与 SDA 建立的先后顺序不能反：
 *              SDA 必须在 SCL 低电平期间改变，高电平期间改变会被当成起始/停止
 *----------------------------------------------------------------------------*/
void NET_I2CSW_WriteByte(uint8_t byte);

#endif /* NET_I2C_SW_H */
