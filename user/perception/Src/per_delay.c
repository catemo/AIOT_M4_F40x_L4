/**
 ******************************************************************************
 * @file    per_delay.c
 * @brief   感知层（perception）—— 微秒级延时底座实现（TIM2 自由计数器）
 *
 *  接口的完整说明（功能/参数/返回值/调用处/注意事项）写在 per_delay.h，
 *  本文件的注释侧重"代码是怎么实现的"。
 *
 *  实现只有三件事：读 CNT、算差值、等够时间。
 *  真正的工程含量在【配置前提】——TIM2 必须已经被配成 1 µs/tick 并启动：
 *    Core/Src/tim.c —— MX_TIM2_Init() 里 Prescaler = 83（84 MHz / 84 = 1 MHz）
 *                      Period = 0xFFFFFFFF（32 位自由向上计数）
 *    同文件 USER CODE 段 —— HAL_TIM_Base_Start(&htim2)（计数器真正开始跑）
 *  这两处缺任何一处，本文件所有延时都会失真（而且是"量级"上的失真）。
 *
 *  ★ 本文件不受"计数器有没有开"的错误检查保护：
 *     TIM2 是 CubeMX 生成的外设底座，本工程默认它一直可用，
 *     所以这里不做 HAL_TIM_Base_Start 的重复调用（重复 Start 会返回 busy）。
 ******************************************************************************
 */
#include "module_cfg.h"
#if PER_DELAY_ENABLE

#include "per_delay.h"
#include "tim.h"       /* extern TIM_HandleTypeDef htim2（CubeMX 生成） */

/*----------------------------------------------------------------------------
 * 函数功能：读取当前微秒计数值（实现：直接取 TIM2 的 CNT 寄存器）
 * 调用处  ：本层两个延时函数 + per_dht11.c   【接口契约见 per_delay.h】
 * 注意事项：① __HAL_TIM_GET_COUNTER 展开后就是读 CNT 寄存器，
 *              没有临界区、没有关中断——因为 32 位对齐读本身是原子的
 *           ② 不调用 __HAL_TIM_SET_COUNTER 去清零计数：
 *              清零会破坏其它并发读数（多人共享一个计数器，谁都不许重置）
 *----------------------------------------------------------------------------*/
uint32_t per_delay_getTickUs(void)
{
    return __HAL_TIM_GET_COUNTER(&htim2);
}

/*----------------------------------------------------------------------------
 * 函数功能：忙等指定微秒数（实现：记录起点，循环做无符号减法直到差值够）
 * 调用处  ：per_dht11.c                      【接口契约见 per_delay.h】
 * 注意事项：① 循环条件是 (now - start) < us —— 无符号减法，回绕自动正确：
 *              若 start = 0xFFFFFF00、翻转后 now = 0x00000080，
 *              则 now - start = 0x180 = 384 µs，与真实经过的时间一致
 *           ② 循环体是空的：忙等就是这样，CPU 在这里空转，
 *              这也正是它只能用于 µs 级短等待的原因
 *----------------------------------------------------------------------------*/
void per_delay_us(uint32_t us)
{
    uint32_t start = per_delay_getTickUs();

    while ((per_delay_getTickUs() - start) < us)
    {
        /* 空转等待：DHT11 的时序不能被打断，这里刻意不做任何让出 CPU 的动作 */
    }
}

/*----------------------------------------------------------------------------
 * 函数功能：忙等指定毫秒数（实现：逐毫秒调用 per_delay_us，避免乘法溢出）
 * 调用处  ：per_dht11.c 起始信号的 18 ms   【接口契约见 per_delay.h】
 * 注意事项：① 为什么不写 per_delay_us(ms * 1000)：
 *              ms > 4294 时 ms * 1000 会 32 位溢出，等的时间会变成错的；
 *              拆成 N 次 1 ms 就没有这个隐患（本例只等 18 ms，但写法要能抗住以后改大）
 *           ② 每次循环都要重读起点：这样 18 次 1 ms 累加出来的总时长
 *              不会因为单次误差累积而漂移
 *----------------------------------------------------------------------------*/
void per_delay_ms(uint32_t ms)
{
    while (ms > 0U)
    {
        per_delay_us(1000U);
        ms--;
    }
}

#endif /* PER_DELAY_ENABLE */
