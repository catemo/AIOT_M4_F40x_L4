/**
 ******************************************************************************
 * @file    per_light.c
 * @brief   感知层（perception）—— 光敏传感器驱动实现（PA5 = ADC1_IN5）
 *
 *  接口的完整说明（功能/参数/返回值/调用处/注意事项）写在 per_light.h，
 *  本文件的注释侧重"四步查询为什么这么写"与"每个参数为什么是它"。
 *
 *  ▍为什么用查询式而不是 DMA / 中断：
 *    光敏是直流缓变量，500 ms 读一次，转换本身只要 0.7 µs。
 *    DMA + 中断 + 缓冲这一套是为"高速连续采样"准备的，用在这里
 *    只会多出几百行初始化与两个回调，收益为零。
 *    查询式的代价是"转换期间阻塞 CPU 约 1 µs"，可以忽略。
 *
 *  ▍为什么句柄是 hadc1 而不是 hadc3：
 *    本板按课件把光敏接在 PA5 = ADC1_IN5；参考工程 L5_xd 接 PF7 = ADC3_IN5。
 *    用错句柄不会报错，只会读到悬空通道的死值（约 1070 且不随光变化），
 *    是这条链最容易踩、也最难自查的坑。
 ******************************************************************************
 */
#include "module_cfg.h"
#if PER_LIGHT_ENABLE

#include "per_light.h"
#include "adc.h"           /* hadc1（Core 生成/手写的 ADC1 句柄） */
#include "main.h"          /* HAL 与 Error_Handler */

/*----------------------------------------------------------------------------
 * 函数功能：光敏传感器初始化（一次空转换预热）
 * 调用处  ：app_light.c 的 app_light_task() 开头
 *----------------------------------------------------------------------------*/
void PER_LIGHT_Init(void)
{
    /* 丢弃第一次转换：复位后内部采样电容处于未定状态，首值常偏低。
     * 用 (void) 是为了明确表达"这里只要副作用、不要结果"，
     * 避免静态检查工具报"返回值未使用"。 */
    (void)PER_LIGHT_ReadRaw();
}

/*----------------------------------------------------------------------------
 * 函数功能：读取一次原始 ADC 值（查询式，四步）
 *----------------------------------------------------------------------------*/
uint16_t PER_LIGHT_ReadRaw(void)
{
    uint16_t value = 0U;

    /* ① 启动：软件触发一次转换。失败（ADC 忙 / 未初始化）直接返回 0，
     *    绝不带着"没启动"的状态往下轮询——那只会白等 10 ms 再失败。 */
    if (HAL_ADC_Start(&hadc1) != HAL_OK)
    {
        return 0U;
    }

    /* ② 等 EOC：10 ms 是"卡故障"而不是"等转换"。
     *    正常转换 0.7 µs，超时说明 ADC 根本没跑起来（时钟/通道配置错）。 */
    if (HAL_ADC_PollForConversion(&hadc1, 10U) == HAL_OK)
    {
        /* ③ 取 DR 寄存器：12 位右对齐，取值 0~4095 */
        value = (uint16_t)HAL_ADC_GetValue(&hadc1);
    }

    /* ④ 停止：单次模式必须停，否则下一次 Start 会返回 BUSY。
     *    用 (void) 忽略返回值：Stop 失败没有补救手段，
     *    下一次 Start 失败时自然会被①拦住。 */
    (void)HAL_ADC_Stop(&hadc1);

    return value;
}

/*----------------------------------------------------------------------------
 * 函数功能：读取一次电压值（整数 mV）
 * 调用处  ：app_light.c 的打印行（低频，不在周期热路径里重复调用）
 *----------------------------------------------------------------------------*/
uint32_t PER_LIGHT_ReadMilliVolt(void)
{
    uint16_t raw = PER_LIGHT_ReadRaw();

    /* 先乘后除：raw × 3300 最大 13.5M，32 位足够；
     * 先除后乘会丢掉整数部分，3300/4095 直接变 0。 */
    return ((uint32_t)raw * PER_LIGHT_VREF_MV) / PER_LIGHT_ADC_MAX;
}

#endif /* PER_LIGHT_ENABLE */
