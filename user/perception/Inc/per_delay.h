/**
 ******************************************************************************
 * @file    per_delay.h
 * @brief   感知层（perception）—— 微秒级延时底座（TIM2 自由计数器）
 *
 *  为什么不用 HAL_Delay：
 *    HAL_Delay 的时基是 TIM6（HAL 时基，1 ms 粒度），做不了微秒级等待；
 *    DHT11 单总线的数据位是 26~70 µs 的脉宽，只能靠微秒计时来分辨 0 和 1。
 *
 *  为什么是 TIM2 而不是 SysTick / DWT：
 *    - SysTick 被 FreeRTOS 独占（任务调度节拍），不能挪用
 *    - DWT 的 CYCCNT 在调试器下载后可能不计数，换个调试环境就翻车
 *    - TIM2 是纯硬件计数器，只读 CNT，不进中断、不抢 CPU，多人读数互不干扰
 *
 *  本底座的三个特点：
 *    - 1 tick = 1 µs（APB1 定时器时钟 84 MHz，Prescaler = 83）
 *    - 32 位向上自由计数（Period = 0xFFFFFFFF），回绕周期约 71.6 分钟
 *    - 只调 HAL_TIM_Base_Start()，从不调 Start_IT()：进中断反而会打断时序测量
 *
 *  ★ 回绕不用管：所有时间差都用 (now - start) 的 32 位无符号减法，
 *    计数器从 0xFFFFFFFF 翻回 0 时减法依然正确（这是无符号减法的性质），
 *    前提是单次测量窗口远小于 71.6 分钟 —— 本例最长只有 18 ms。
 *
 *  ★ 本层是感知层【内部】工具，只有同层的 per_dht11.c 会 include；
 *    应用层禁止直接 include 本文件（也禁止直接用它做业务延时——
 *    业务节拍一律用 FreeRTOS 的 osDelay，让出 CPU）。
 ******************************************************************************
 */
#ifndef PER_DELAY_H
#define PER_DELAY_H

#include <stdint.h>

/*----------------------------------------------------------------------------
 * 函数功能：读取当前微秒计数值（TIM2 的 CNT 快照）
 * 参数    ：无
 * 返回值  ：当前 TIM2 计数值（单位 µs，32 位自由递增、会自然回绕）
 * 调用处  ：本层 per_delay_us() / per_delay_ms()，
 *          以及 per_dht11.c 里所有"等电平 / 测脉宽"的地方
 * 注意事项：① 返回值本身没有意义，有意义的是【两次读数之差】
 *           ② 只读 CNT，不做任何修改，所以多个调用者并发读是安全的
 *           ③ 本函数代替的是 DWT 的 CYCCNT：后者在调试器下载后可能不计数，
 *              而 TIM2 只要时钟在就一定在跑
 *----------------------------------------------------------------------------*/
uint32_t per_delay_getTickUs(void);

/*----------------------------------------------------------------------------
 * 函数功能：忙等指定的微秒数（精度 ±1 µs，阻塞、不让出 CPU）
 * 参数    ：us —— 要等待的微秒数（本例用到 30 / 100 µs 这类小值）
 * 返回值  ：无
 * 调用处  ：per_dht11.c 的起始信号保持、读位间隙等时序关键处
 * 注意事项：① ★ 这是忙等：期间 CPU 100% 空转，且【不关中断】时会被打断，
 *              所以只用在 µs 级短等待；毫秒级以上一律交给 osDelay 或 per_delay_ms
 *           ② 回绕安全：用 (now - start) 无符号减法判断，跨 0xFFFFFFFF 也正确
 *           ③ 不要用它做任务节拍——那会让低优先级任务饿死
 *----------------------------------------------------------------------------*/
void per_delay_us(uint32_t us);

/*----------------------------------------------------------------------------
 * 函数功能：忙等指定的毫秒数（供 DHT11 起始信号 18 ms 这种"必须忙等"的场合）
 * 参数    ：ms —— 要等待的毫秒数（本例只用 18）
 * 返回值  ：无
 * 调用处  ：per_dht11.c 发送起始信号时拉低总线的 18 ms
 * 注意事项：① 刻意用"1 ms × N 次"而不是 per_delay_us(ms * 1000)：
 *              后者在 ms > 4294 时会 32 位溢出，前者不会有这个问题
 *           ② ★ 2026-10-30 修正：DHT11 起始信号的 18 ms 已改走 osDelay
 *              （见 per_dht11.c 的 dht11_start_low_wait）——旧注释
 *              "osDelay 中途被切走会破坏时序"是错误认知：拉低只写一次 ODR，
 *              引脚电平由硬件保持，CPU 睡着不影响总线。本函数因此降级为
 *              "调度器未运行时的防御回退路径"，正常业务毫秒等待一律 osDelay
 *           ③ 本工程不再有任何"必须长忙等"的场景：需要 CPU 醒着的只有
 *              DHT11 关中断的 4~5 ms 时序关键段，那段用的是逐 µs 忙等
 *----------------------------------------------------------------------------*/
void per_delay_ms(uint32_t ms);

#endif /* PER_DELAY_H */
