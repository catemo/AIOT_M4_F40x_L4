/**
 ******************************************************************************
 * @file    per_iwdg.h
 * @brief   感知层（perception）—— 独立看门狗 IWDG 驱动接口（片上外设，不占引脚）
 *
 *  IWDG 是什么：
 *    片上独立看门狗（Independent Watchdog）。程序跑飞 / 卡死时没人喂狗，
 *    计数器倒到 0 就自动复位系统，让设备"自己把自己救回来"。
 *
 *  三个关键词（与课件 2.4 一致）：
 *    LSI 独立时钟 —— 时钟源是片上 LSI（≈32 kHz），主时钟停了它还在走；
 *                    且 IWDG 一旦启动，硬件会强制打开 LSI，不需要也不允许
 *                    软件再去碰 RCC 的 LSI 使能位。
 *    喂狗 Refresh —— 往 KR 写 0xAAAA 把计数器重载回设定值，
 *                    "死亡倒计时"重新开始（HAL 封装为 HAL_IWDG_Refresh）。
 *    不可停止     —— 启动之后软件无法关闭，只有系统复位才能让它重来。
 *                    这正是"演示卡死会真复位"的前提。
 *
 *  超时怎么算（参数在 cfg_param.h，两数相乘除 32）：
 *    timeout_ms = PER_IWDG_DIV × PER_IWDG_RELOAD / 32
 *               = 64 × 1500 / 32 = 3000 ms
 *    ★ 不要用 CubeMX 默认的 4 / 4095（≈0.5 s）：引导流程还没跑完就咬狗，
 *      上电即陷入"复位 → 重启 → 再复位"的死循环。
 *
 *  调试冻结：
 *    调试器 halt 住 CPU 时 LSI 仍在计数，halt 超过 3 秒 IWDG 照样复位，
 *    把单步调试打断。本驱动在初始化时调用 __HAL_DBGMCU_FREEZE_IWDG()：
 *    halt 期间 IWDG 停止计数，放开后继续（F4 的宏名没有 "1"，H7 才有）。
 *
 *  复位原因检测：
 *    RCC_CSR 的 IWDGRSTF 标志记录"上次复位是不是 IWDG 触发的"。
 *    应用层上电先读一次、随即清掉（查完即清，否则下次上电误判），
 *    就能把"被狗咬醒的"与"正常上电"区分开打印出来。
 *
 *  为什么这条链只有两层（app → perception）：
 *    与 DHT11 链同一个判据——中间没有"协议位 / 语义动作"这类知识，
 *    硬塞一层平台层只会多出几行纯转发代码。
 *    RCC 复位标志这种"硬件细节"也收在本层，应用层不见寄存器。
 ******************************************************************************
 */
#ifndef PER_IWDG_H
#define PER_IWDG_H

#include <stdint.h>

/*----------------------------------------------------------------------------
 * 函数功能：启动独立看门狗（超时 = PER_IWDG_TIMEOUT_MS，本例 3000 ms）
 * 参数    ：无（分频与重载来自 cfg 横切层 cfg_param.h 的 PER_IWDG_DIV / RELOAD）
 * 返回值  ：无
 * 调用处  ：应用层 app_watchdog.c 的任务开头，整个程序只调一次
 * 注意事项：① ★ 一旦启动不可停止：从本函数返回那一刻起，
 *              必须每 PER_IWDG_TIMEOUT_MS 内喂一次狗，否则系统复位
 *           ② 本函数同时做两件小事：
 *              - __HAL_DBGMCU_FREEZE_IWDG()：调试 halt 时冻结计数
 *              - 启动后立刻喂一次：给引导流程留满一个完整超时窗口
 *           ③ LSI 不用软件使能：IWDG 启动时硬件强制打开 LSI
 *           ④ PER_IWDG_DIV 填了非法值时进 Error_Handler() 停机
 *             （正常情况下 cfg_check.h 的闸门会在编译期先拦住）
 *----------------------------------------------------------------------------*/
void PER_IWDG_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：喂狗（重载递减计数器，"死亡倒计时"重新开始）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：应用层 app_watchdog.c 的喂狗循环（每 APP_WDT_FEED_PERIOD_MS 一次）
 * 注意事项：① 必须在超时（本例 3 秒）之前调用，晚一次系统就复位
 *           ② 这是"保命"的唯一动作——启动后没有任何办法能停狗，
 *              只有按时喂；演示卡死正是靠"故意不喂"触发复位
 *----------------------------------------------------------------------------*/
void PER_IWDG_Feed(void);

/*----------------------------------------------------------------------------
 * 函数功能：查询上次复位是否由 IWDG 触发
 * 参数    ：无
 * 返回值  ：1 = 上次是被看门狗咬醒的；0 = 上电 / 其它原因复位
 * 调用处  ：应用层 app_watchdog.c 任务开头（打印复位原因）
 * 注意事项：① 读的是 RCC_CSR 的 IWDGRSTF 标志位，读后【不会】自动清零——
 *              必须紧跟着调 PER_IWDG_ClearResetFlags()，否则下次上电
 *              会把"上电复位"误报成"看门狗复位"
 *           ② 为什么"先读后清"要分两个函数而不是合成一个：
 *              读与清之间隔着打印等操作，合成一个就把"读到什么"
 *              藏进了黑盒，排障时无法单独复现标志位
 *----------------------------------------------------------------------------*/
uint8_t PER_IWDG_LastResetByIwdg(void);

/*----------------------------------------------------------------------------
 * 函数功能：清除全部复位原因标志（RCC_CSR 的 RMVF 位）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：紧跟 PER_IWDG_LastResetByIwdg() 之后调用一次
 * 注意事项：① 它清的是【全部】复位标志（上电 / 引脚 / 软件 / IWDG / WWDG…），
 *              不是只清 IWDG 那一位——所以没有"先清后读"的机会，
 *              顺序永远是先读、再清
 *           ② 只在启动时调一次即可，不要放进周期循环：
 *              循环里清标志会让真正的 IWDG 复位也被误报成"上电"
 *----------------------------------------------------------------------------*/
void PER_IWDG_ClearResetFlags(void);

#endif /* PER_IWDG_H */
