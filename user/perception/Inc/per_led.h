/**
 ******************************************************************************
 * @file    per_led.h
 * @brief   感知层（perception）—— LED 统一接口（1 颗灯：开关语义）
 *
 *  本层职责：给上层一套"与硬件无关"的名字和函数（PER_LED_*），
 *  把本层内 per_gpio 的枚举名与函数名挡在后面。
 *
 *  ★ 关键规矩：上层（app_blink / app_led）只许 include 本文件，
 *    永远不许 include per_gpio.h —— 这就是感知层"门卫"存在的意义。
 *
 *  本层存在的意义：把"哪块板子"这件事挡在下面。
 *  日后改用 PWM 调光、换成灯带、一颗灯换成三颗 —— 改本层几行，
 *  应用层一行不动。分层买的就是这份"改代码的效率"。
 *
 *  硬件对应：0 = LED1 / PG14（低电平点亮）
 *
 *  ★ 串口控灯章节：本层从"只会翻转"扩到"能点亮 / 熄灭 / 查询"四个动作
 *    （Toggle 供闪烁用，On / Off / IsOn 供串口命令用），
 *    亮灭方向的翻译仍在 per_gpio 的 s_led_hw[] 表里，本层不做判断。
 ******************************************************************************
 */
#ifndef PER_LED_H
#define PER_LED_H

#include <stdint.h>

/* ===================== LED 编号（本层对外独立定义，屏蔽驱动细节） ===================== */
/**
 * @brief 感知层对外的 LED 编号，和 per_gpio 内部编号互相独立（解耦）
 * @note  本层编号可与 per_gpio 编号一一对应，也可以是任意映射关系，改一边不影响另一边；
 *        PER_LED_COUNT 放在最后，它的值自动等于灯的总数，用于越界判断
 */
typedef enum
{
    PER_LED1 = 0,      /* LED1（硬件：PG14） */
    PER_LED_COUNT      /* 哨兵：灯的总数（本例 = 1），必须放最后 */
} PER_LED_t;

/* ===================== 返回码 ===================== */
#define PER_LED_OK        0   /* 成功 */
#define PER_LED_ERR_PARAM 1   /* 参数错误（LED 编号越界） */

/*----------------------------------------------------------------------------
 * 函数功能：初始化 LED 硬件（转发 per_gpio_init，幂等）
 * 参数    ：无
 * 返回值  ：PER_LED_OK(0) = 成功（下层返回码原样上抛，本层不加工）
 * 调用处  ：app_blink.c 的 APP_BLINK_Init()
 *           （完整初始化链：app_led_init → APP_BLINK_Init → 本函数 → per_gpio_init）
 * 注意事项：① 必须在任何灯操作之前调用一次；引脚没初始化就点灯，写寄存器全部无效
 *           ② 本层对初始化不做任何加工——引脚怎么配是驱动细节的事，
 *              本层只负责"把命令按层级往下传"
 *----------------------------------------------------------------------------*/
uint8_t PER_LED_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：点亮指定编号的 LED（串口控灯章节新增）
 * 参数    ：led —— 感知层 LED 编号，取值 PER_LED1(0)
 * 返回值  ：PER_LED_OK(0) = 成功；PER_LED_ERR_PARAM(1) = 编号越界
 * 调用处  ：app_blink.c 的 APP_BLINK_On()
 *           （完整调用链：app_cmd 收到 "LED1 ON" → APP_BLINK_On → 本函数
 *             → per_gpio_write → HAL_GPIO_WritePin）
 * 注意事项：① 与 Toggle 的失败策略一致：越界就返回错误码，让上层感知到
 *           ② 本层不做"亮灭方向"的判断：点亮就是点亮，
 *              写成高还是低由 per_gpio 查表决定（换板子只改那张表）
 *----------------------------------------------------------------------------*/
uint8_t PER_LED_On(PER_LED_t led);

/*----------------------------------------------------------------------------
 * 函数功能：熄灭指定编号的 LED（串口控灯章节新增）
 * 参数    ：led —— 感知层 LED 编号，取值 PER_LED1(0)
 * 返回值  ：PER_LED_OK(0) = 成功；PER_LED_ERR_PARAM(1) = 编号越界
 * 调用处  ：app_blink.c 的 APP_BLINK_Off()
 * 注意事项：与 PER_LED_On() 完全对称：先查编号，再交给 per_gpio_write
 *----------------------------------------------------------------------------*/
uint8_t PER_LED_Off(PER_LED_t led);

/*----------------------------------------------------------------------------
 * 函数功能：查询指定编号 LED 的真实亮灭状态（串口控灯章节新增）
 * 参数    ：led —— 感知层 LED 编号，取值 PER_LED1(0)
 * 返回值  ：1 = 亮；0 = 灭（编号越界时返回 0，即"当作灭"）
 * 调用处  ：app_blink.c 的 APP_BLINK_IsOn()
 *           （完整调用链：app_cmd 收到 "STATUS" → APP_BLINK_IsOn → 本函数
 *             → per_gpio_is_on → HAL_GPIO_ReadPin）
 * 注意事项：① 读真实引脚电平，本层与 per_gpio 都不缓存状态——
 *              串口 STATUS 命令回的永远是"硬件实际状态"，
 *              不会与"软件以为的状态"打架（排障时这点很关键）
 *           ② 查询接口不返回错误码：越界当作灭，避免上层为查个状态写分支
 *----------------------------------------------------------------------------*/
uint8_t PER_LED_IsOn(PER_LED_t led);

/*----------------------------------------------------------------------------
 * 函数功能：翻转指定编号的 LED 状态（带越界检查）
 * 参数    ：led —— 感知层 LED 编号，取值 PER_LED1(0)
 * 返回值  ：PER_LED_OK(0) = 成功；PER_LED_ERR_PARAM(1) = 编号越界
 * 调用处  ：app_blink.c 的 APP_BLINK_process()（闪烁状态机数够半周期时调用）
 *           （完整调用链：APP_BLINK_process → 本函数 → per_gpio_toggle
 *             → HAL_GPIO_TogglePin → PG14 取反）
 * 注意事项：① 编号越界返回错误码而不是静默跳过——本层要让上层"感知到"
 *              传错了参数；per_gpio 那边才是静默防御（职责不同，失败策略不同）
 *           ② 强转成立的前提是 PER_LEDn 与 PER_GPIO_LEDn 编号顺序一致；
 *              将来驱动表改了枚举顺序，必须同步改本文件
 *----------------------------------------------------------------------------*/
uint8_t PER_LED_Toggle(PER_LED_t led);

#endif /* PER_LED_H */
