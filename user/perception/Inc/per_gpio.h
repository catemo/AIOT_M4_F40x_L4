/**
 ******************************************************************************
 * @file    per_gpio.h
 * @brief   感知层（perception）—— GPIO 驱动接口（本例 1 颗灯：LED1 = PG14）
 *
 *  本层只关心"硬件怎么点灯"，不管"灯为什么亮"。
 *    - 灯的硬件描述全在 per_gpio.c 的 s_led_hw[] 表里，
 *      换板子 / 换引脚 / 亮灭反了只改那张表，本头文件和上层代码一行都不用动
 *    - LED1 = PG14（GPIOG），低电平点亮；RCC 时钟挂在 GPIOG
 *    - 对外暴露四个动作：初始化（init）、写亮灭（write）、读亮灭（is_on）、翻转（toggle），
 *      不掺任何业务逻辑
 *    - write / is_on 是"亮/灭"语义，靠 s_led_hw[].active_low 在"高低电平"之间翻译；
 *      toggle 与 active_low 无关（只翻 ODR），三者分工不同
 *
 *  ★ 本层红线：不做业务判断，不认识"闪烁"。
 *  ★ 本文件只有感知层内的 per_led.c 会 include——
 *    应用层禁止直接 include 本文件，必须走 per_led.h。
 ******************************************************************************
 */
#ifndef PER_GPIO_H
#define PER_GPIO_H

#include <stdint.h>

/**
 * @brief LED 编号（本层自己的名字，从 0 开始，与板上丝印 LED1 对应）
 * @note  ① 这个编号只在本层有意义：与应用层的编号互相独立，
 *          任一层增删灯具或改名都不波及别层
 *        ② PER_GPIO_LED_COUNT 放在最后，它的值自动等于灯的总数，
 *          既用来定义 s_led_hw[] 表长度，也用来做越界判断
 */
typedef enum
{
    PER_GPIO_LED1 = 0,     /* LED1 = PG14，低电平点亮 */
    PER_GPIO_LED_COUNT     /* 哨兵：灯的总数（本例 = 1） */
} PER_GPIO_LED_t;

/* ===================== 返回码 ===================== */
#define PER_GPIO_LED_OK        0   /* 成功 */
#define PER_GPIO_LED_ERR_PARAM 1   /* 参数错误（LED 编号越界） */

/*----------------------------------------------------------------------------
 * 函数功能：初始化 LED 引脚（时钟 + 推挽输出 + 先置为熄灭）
 * 参数    ：无
 * 返回值  ：PER_GPIO_LED_OK(0) = 成功（本函数不做校验，当前实现固定返回成功）
 * 调用处  ：感知层 per_led.c 的 PER_LED_Init()
 *           （完整初始化链：app_led_init → APP_BLINK_Init → PER_LED_Init → 本函数）
 * 注意事项：① 时钟必须先开：GPIOG 时钟没使能时，后面所有寄存器写操作全部无效，
 *              表现是"程序不报错，但灯就是不亮"
 *           ② 低电平点亮的灯，"灭" = 写高电平(SET)，写反了会一上电就常亮
 *           ③ 幂等：重复调用只是把寄存器重写一遍，不会把状态搞乱
 *----------------------------------------------------------------------------*/
uint8_t per_gpio_init(void);

/*----------------------------------------------------------------------------
 * 函数功能：把指定 LED 设置成"亮"或"灭"（串口控灯章节新增）
 * 参数    ：led —— 本层 LED 编号，取值 PER_GPIO_LED1(0)
 *           on  —— 1 = 点亮；0 = 熄灭（传其它值按"真"处理）
 * 返回值  ：无（void）；编号越界时什么也不做，直接返回
 * 调用处  ：感知层 per_led.c 的 PER_LED_On() / PER_LED_Off()
 *           （完整调用链：APP_BLINK_On → PER_LED_On → 本函数 → HAL_GPIO_WritePin）
 * 注意事项：① ★ 本函数与 toggle 的根本差别：亮/灭是"语义"，要经过
 *              s_led_hw[].active_low 翻译成高/低电平——
 *              低电平点亮的灯，"亮" = 写 RESET；高电平点亮的灯，"亮" = 写 SET。
 *              正因为有了这个翻译，上层才敢说"点亮"而不必知道接法
 *           ② 这也是 s_led_hw[] 表里 active_low 字段在本册才第一次被真正用上：
 *              闪烁（toggle）不需要它，串口控灯（ON/OFF）需要它
 *           ③ 与 toggle 一样做越界兜底：非法编号宁可不动，也不误碰别的引脚
 *----------------------------------------------------------------------------*/
void per_gpio_write(PER_GPIO_LED_t led, uint8_t on);

/*----------------------------------------------------------------------------
 * 函数功能：查询指定 LED 当前是亮还是灭（串口控灯章节新增）
 * 参数    ：led —— 本层 LED 编号，取值 PER_GPIO_LED1(0)
 * 返回值  ：1 = 亮；0 = 灭（编号越界时返回 0，即"当作灭"）
 * 调用处  ：感知层 per_led.c 的 PER_LED_IsOn()
 *           （完整调用链：APP_BLINK_IsOn → PER_LED_IsOn → 本函数 → HAL_GPIO_ReadPin）
 * 注意事项：① 读的是【真实引脚电平】，不是软件记忆值——
 *              排障时"软件以为的"和"硬件实际的"不会打架
 *           ② 与 write 成对：同一个 active_low 做反向翻译
 *              （低电平点亮 → 读到低电平才算"亮"）
 *           ③ 越界返回 0（灭）而不是报错：查询类接口不打断调用者，
 *              与"写操作越界就什么都不做"是同一套静默兜底策略
 *----------------------------------------------------------------------------*/
uint8_t per_gpio_is_on(PER_GPIO_LED_t led);

/*----------------------------------------------------------------------------
 * 函数功能：翻转指定 LED 的电平（亮 ↔ 灭切换一次）
 * 参数    ：led —— 本层 LED 编号，取值 PER_GPIO_LED1(0)
 * 返回值  ：无（void）；编号越界时什么也不做，直接返回
 * 调用处  ：感知层 per_led.c 的 PER_LED_Toggle()
 *           （完整调用链：APP_BLINK_process → PER_LED_Toggle → 本函数
 *             → HAL_GPIO_TogglePin → PG14 取反）
 * 注意事项：① 越界检查放在本层是"最后一道堤坝"：非法编号宁可什么都不做，
 *              也绝不能去动别的引脚（防止程序跑飞误操作外设）
 *           ② 翻转只对输出寄存器(ODR)做一次异或，与 active_low 无关——
 *              所以不需要关心这颗灯到底是高电平点亮还是低电平点亮
 *----------------------------------------------------------------------------*/
void per_gpio_toggle(PER_GPIO_LED_t led);

#endif /* PER_GPIO_H */
