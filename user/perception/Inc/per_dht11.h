/**
 ******************************************************************************
 * @file    per_dht11.h
 * @brief   感知层（perception）—— DHT11 温湿度传感器驱动接口（PG9 单总线）
 *
 *  硬件连接：
 *    DHT11 DATA → PG9（CubeMX 已配成推挽输出、上电高电平，User Label = DHT11）
 *    模块 VCC → 3.3 V，GND → GND
 *    ★ 模块内通常已集成 4.7k~10k 上拉；用裸传感器时必须在 DATA 与 VCC 之间
 *      外接上拉电阻，否则总线永远拉不高 → 一直报 stage=1（完全没回应）
 *
 *  通信协议（单总线：一根 DATA 线靠"脉宽"传递信息）：
 *    ① 主机起始信号：拉低 ≥18 ms → 拉高 20~40 µs
 *    ② DHT11 响应：拉低 80 µs → 拉高 80 µs
 *    ③ 数据 40 位（5 字节）：每位以 50 µs 低电平开头，
 *       随后的高电平 26~28 µs = 0，约 70 µs = 1（★ 本驱动用 >40 µs 判 1）
 *    ④ 数据格式：湿度整 / 湿度小 / 温度整 / 温度小 / 校验和
 *    ⑤ 校验和 = 前 4 字节之和 & 0xFF（不等则整帧丢弃）
 *
 *  三个定时器的分工（本驱动只用其中一个）：
 *    - SysTick → FreeRTOS 独占（任务调度节拍），本驱动不碰
 *    - TIM6    → HAL 时基（HAL_Delay 的背后），本驱动不用
 *    - TIM2    → 微秒计时，统一走同层 per_delay.h（只读 CNT，1 tick = 1 µs）
 *
 *  ★ 为什么要关中断：
 *    数据位是 26~70 µs 的脉宽，任务切换或任意中断把 CPU 抢走几百微秒，
 *    位宽就测错了。故从"拉高起始信号"到"读完 40 位"之间调用 __disable_irq()，
 *    约 4~5 ms/次。相对 2 秒采集周期占比不到 0.3%，期间 DMA 仍照常收串口数据
 *    （DMA 是硬件搬运，不依赖 CPU 响应中断）。
 *
 *  ★ 失败阶段（stage）是"报得清"的关键：
 *    串口打印一个 1~6 的数字，就能判断卡在哪一步——
 *    看到 1 去查接线供电，看到 6 去查电气质量，而不是笼统地"读不到数"。
 ******************************************************************************
 */
#ifndef PER_DHT11_H
#define PER_DHT11_H

#include <stdint.h>

/**
 * @brief DHT11 读取结果状态
 */
typedef enum
{
    PER_DHT11_OK           = 0,   /* 读取成功，校验通过 */
    PER_DHT11_ERR_TIMEOUT  = 1,   /* 响应/数据位超时（没接好 / 时序断） */
    PER_DHT11_ERR_CHECKSUM = 2    /* 40 位读到了但校验和对不上 */
} PER_DHT11_Status_t;

/**
 * @brief DHT11 数据（原始 8 位字段，不做任何换算）
 * @note  本层只负责"把 40 位读准"，不负责换算成"多少摄氏度"——
 *        小数部分如何解释、要不要做偏移校准，都是应用层的事。
 *        DHT11 的小数部分实际恒为 0，保留字段是为了与协议格式对齐。
 */
typedef struct
{
    uint8_t humidity_int;      /* 湿度整数部分 (%) */
    uint8_t humidity_dec;      /* 湿度小数部分 (%) */
    uint8_t temperature_int;   /* 温度整数部分 (℃) */
    uint8_t temperature_dec;   /* 温度小数部分 (℃) */
} PER_DHT11_Data_t;

/**
 * @brief 读取失败阶段（串口打印的 stage 字段就是它）
 * @note  1      = 完全没回应  → 查供电 / 接线 / 上拉 / 模块本身
 *        2 / 3  = 响应只回了一半 → 查上拉 / 接触不良 / 线太长
 *        4 / 5  = 有回应但数据段异常 → 查电源纹波 / 线长 / 上拉
 *        6      = 校验和错 → 多为电气质量问题（干扰、供电不足）
 */
typedef enum
{
    PER_DHT11_FAIL_NONE      = 0,
    PER_DHT11_FAIL_RESP_LOW  = 1,   /* 等"响应低电平"超时（传感器完全没应答） */
    PER_DHT11_FAIL_RESP_HIGH = 2,   /* 等"响应高电平"超时 */
    PER_DHT11_FAIL_RESP_END  = 3,   /* 等"响应结束（准备收数据）"超时 */
    PER_DHT11_FAIL_BIT_LOW   = 4,   /* 数据位：等低电平超时 */
    PER_DHT11_FAIL_BIT_HIGH  = 5,   /* 数据位：测高电平脉宽超时 */
    PER_DHT11_FAIL_CHECKSUM  = 6    /* 40 位读完但校验和不符 */
} PER_DHT11_FailStage_t;

/*----------------------------------------------------------------------------
 * 函数功能：DHT11 初始化（把 PG9 恢复成总线空闲态：推挽输出 + 高电平）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：应用层 app_dht11.c 的任务开头（完整链：app_dht11_task → 本函数）
 * 注意事项：① CubeMX 的 MX_GPIO_Init 已经把 PG9 配成输出高电平，
 *              这里再配一次是为了"幂等 + 不依赖 MX 配置"：
 *              万一 .ioc 里上电电平被改成 Low，本函数也会把它拉回空闲态
 *           ② 没有它，起始信号发出去之前总线自己就是低的，
 *              DHT11 永远等不到"下降沿"，表现就是一直 stage=1
 *----------------------------------------------------------------------------*/
void PER_DHT11_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：读取一次温湿度（阻塞式，约 25 ms；失败时 data 内容保持不变）
 * 参数    ：data —— 输出数据结构体指针（NULL 时直接返回 ERR_TIMEOUT）
 * 返回值  ：PER_DHT11_OK / ERR_TIMEOUT / ERR_CHECKSUM
 * 调用处  ：应用层 app_dht11.c 的采集循环（失败时它负责重试）
 * 注意事项：① ★ 本函数内部会 __disable_irq() / __enable_irq()，且成对出现：
 *              所有退出路径（含超时 goto）都汇到同一个出口再开中断，
 *              否则一次超时就会让系统永远关着中断 —— 这是本驱动最容易写错的地方
 *           ② 读取间隔必须 ≥1 秒（DHT11 最快 1 Hz），本工程用 2 秒；
 *              连着狂读会得到上一次的旧数据或直接超时
 *           ③ 失败时【不改写 data】：应用层可以放心沿用上一次的值做联动，
 *              这正是"读失败时 LED 保持现状"的实现基础
 *           ④ 本函数是忙等式的：25 ms 内不响应任务调度。
 *              它不该被放进高优先级任务里
 *----------------------------------------------------------------------------*/
PER_DHT11_Status_t PER_DHT11_Read(PER_DHT11_Data_t *data);

/*----------------------------------------------------------------------------
 * 函数功能：取最近一次读取的失败阶段（成功时为 FAIL_NONE = 0）
 * 参数    ：无
 * 返回值  ：PER_DHT11_FailStage_t（1~6 的含义见上方枚举）
 * 调用处  ：应用层 app_dht11.c 打印诊断信息
 * 注意事项：① ★ 这是【全局单一变量】而不是塞进 data 结构体：
 *              因为失败时 data 根本没被写入，调用者拿不到东西，
 *              失败原因只能单独汇报（这也让"读失败时的诊断"与"读成功时的值"
 *              两条路径互不干扰）
 *           ② 每次 Read 开头都会把它清零，所以读到的一定是最近一次的结果
 *----------------------------------------------------------------------------*/
PER_DHT11_FailStage_t PER_DHT11_GetLastFailStage(void);

/**
 * @brief 自检诊断结果（感知层负责测出这些物理量，应用层负责把它们变成文本）
 * @note  为什么不是一个"打印函数"：打印要走上层的 mod_uart1 → net_uart，
 *        感知层依赖上层会让依赖方向倒转、分层直接破产。
 *        所以这里只回填数字，"怎么表达"由应用层决定。
 */
typedef struct
{
    uint32_t tim2_delta_us;     /* TIM2 延时 1000 µs 的实测差值（应 ≈1000） */
    uint8_t  loopback_high;     /* 输出高后读回（应为 1） */
    uint8_t  loopback_low;      /* 输出低后读回（应为 0） */
    uint8_t  idle_bus;          /* 空闲总线电平（应为 1；0 = 被外部拉低） */
    uint32_t resp_low_samples;  /* 应答窗口内低电平采样数（0 = 传感器完全无应答） */
} PER_DHT11_Diag_t;

/*----------------------------------------------------------------------------
 * 函数功能：DHT11 硬件自检（只做探测、不做打印，约 25 ms）
 * 参数    ：diag —— 诊断结果输出结构体（NULL 时直接返回）
 * 返回值  ：无
 * 调用处  ：应用层 app_dht11.c 任务开头，启动只跑一次
 * 注意事项：① 诊断项各自回答一个问题，看到异常就知道该去查哪：
 *              tim2_delta ≈ 1000     → 否则 TIM2 没跑或 PSC 配错，所有 µs 计时都错
 *              loopback = 1, 0       → 否则 PG9 引脚不通（焊点 / 引脚号写错）
 *              idle_bus = 1          → 0 = 被外部拉低（短路 / 缺上拉）
 *              resp_low_samples = 0  → 传感器完全没应答；> 0 = 有应答但时序不对
 *           ② 自检内部会发一次完整起始信号，所以它会占用约 25 ms，
 *              只适合启动时跑一次，不要放进周期循环
 *           ③ 定位完成后可以把调用删掉——它是诊断工具，不是产品功能
 *----------------------------------------------------------------------------*/
void PER_DHT11_SelfTest(PER_DHT11_Diag_t *diag);

#endif /* PER_DHT11_H */
