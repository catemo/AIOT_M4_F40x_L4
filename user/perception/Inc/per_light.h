/**
 ******************************************************************************
 * @file    per_light.h
 * @brief   感知层（perception）—— 光敏传感器驱动接口（PA5 = ADC1_IN5）
 *
 *  硬件原理（分压电路）：
 *     VDD3V3 ── R(固定) ──┬── PA5 / ADC1_IN5
 *                         │
 *                      R(光敏)
 *                         │
 *                        GND
 *   光照越强 → 光敏电阻阻值越小 → 分压点电压越低 → ADC 值越小。
 *   所以"ADC 大 = 环境暗"，方向与本能的"数大＝亮"相反，
 *   等级判定（app_light）必须按这个方向写。
 *
 *  典型参考值（随硬件/环境变化，仅供判断接线是否正常）：
 *    强光（手机手电照住）≈ 100~300
 *    室内自然光           ≈ 400~800
 *    手完全遮挡           ≈ 900~1500
 *   ★ 若读数恒定在 1070 附近且遮不遮都一样，先查是不是误用了 hadc3：
 *     本板光敏在 PA5/ADC1_IN5，参考工程 L5_xd 在 PF7/ADC3_IN5，
 *     用错句柄读到的是悬空通道的"死值"，看起来像传感器坏了。
 *
 *  采集方式：查询式单次转换（软件触发，不用 DMA / 不用中断）
 *    HAL_ADC_Start → HAL_ADC_PollForConversion(10 ms) → HAL_ADC_GetValue → HAL_ADC_Stop
 *    ADCCLK = PCLK2 84 MHz ÷ 4 = 21 MHz，采样 3 周期，
 *    单次转换约 (3 + 12) / 21 MHz ≈ 0.7 µs——远快于光敏需要的响应速度。
 *
 *  ★ 本层只负责"把引脚电压变成数字"，不判定"亮还是暗"：
 *    阈值、等级、点灯都是应用层的事。感知层不知道"光"是什么。
 ******************************************************************************
 */
#ifndef PER_LIGHT_H
#define PER_LIGHT_H

#include <stdint.h>

#define PER_LIGHT_ADC_MAX   4095U   /* 12 位 ADC 满量程 */
#define PER_LIGHT_VREF_MV   3300U   /* 参考电压 3.3 V（单位 mV） */

/*----------------------------------------------------------------------------
 * 函数功能：光敏传感器初始化（做一次空转换预热）
 * 参数    ：无
 * 返回值  ：无
 * 调用处  ：应用层 app_light.c 的任务开头
 * 注意事项：① ADC1 本体由 main() 里的 MX_ADC1_Init() 初始化，本函数不重复配置；
 *              预热是为了丢弃复位后第一次转换（内部采样电容初始状态会让首值偏低）
 *           ② 重复调用无副作用：预热只是多读一次，不改变任何状态
 *----------------------------------------------------------------------------*/
void PER_LIGHT_Init(void);

/*----------------------------------------------------------------------------
 * 函数功能：读取一次原始 ADC 值（查询式阻塞，约 1 µs）
 * 参数    ：无
 * 返回值  ：0~4095；HAL_ADC_Start 失败或转换超时返回 0
 * 调用处  ：应用层 app_light.c 的采集循环（做 4 点滑动平均）
 * 注意事项：① ★ 失败返回 0 与"真的全亮"数值相同，这是本驱动的固有歧义
 *              （课件 2.8 的写法就是这样）：光敏分压正常工作时极少到 0，
 *              若持续看到 0，先查 PA5 是否接好、ADC1 时钟是否使能
 *           ② 超时 10 ms 是"远大于转换时间（0.7 µs）"的安全值，
 *              目的是卡住"ADC 没启动成功"这种故障，而不是给转换留时间
 *           ③ 本函数不做滤波、不做校准：那是应用层的事，
 *              本层保持"读一次就是一次真实转换"的单一语义
 *----------------------------------------------------------------------------*/
uint16_t PER_LIGHT_ReadRaw(void);

/*----------------------------------------------------------------------------
 * 函数功能：读取一次电压值（整数 mV，避免浮点库）
 * 参数    ：无
 * 返回值  ：0~3300 mV（按 raw × 3300 / 4095 换算）
 * 调用处  ：应用层 app_light.c 的打印行（与 ADC 值一起报）
 * 注意事项：① 用整数运算而不是 float：本工程不引入浮点格式化库，
 *              整数除法的误差 ≤1 mV，对"看趋势"完全够用
 *           ② 它是"再读一次"而不是"取上一次的值"：与 ReadRaw 一样是即时转换，
 *              两次调用之间光可能已经变了——所以应用层应当先读 raw 再自己换算，
 *              只有"只想要电压"的场合才单独调本函数
 *----------------------------------------------------------------------------*/
uint32_t PER_LIGHT_ReadMilliVolt(void);

#endif /* PER_LIGHT_H */
