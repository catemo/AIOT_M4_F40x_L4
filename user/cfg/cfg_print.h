/**
 ******************************************************************************
 * @file    cfg_print.h
 * @brief   cfg 横切配置层 —— 串口调试打印开关（总闸 + 闸门）
 *
 *  本文件是 module_cfg.h 的子文件（由 module_cfg.h 统一包含），不要单独包含。
 *  定位：全工程所有往串口打调试信息的开关都集中在这里——定位问题时全开，
 *        稳定后把总闸拨 0 一键静默，或单独关掉某个模块的分闸。
 *
 *  ★ 本例（IOT_M4_L4）情况说明：
 *    串口链已经接入（MOD_UART1_ENABLE = 1），但本册的串口只干两件"正经业务"——
 *    命令回复、以及每 2 秒一行的温湿度读数，都用 MOD_UART1_SendString 直出，
 *    不走调试打印体系，所以总闸保持 0。
 *    ★ 为什么业务输出不走打印体系：打印是"开发期工具"，业务输出是"产品功能"。
 *      把温湿度读数塞进打印体系，就会连"关掉调试打印"一起把功能关掉——
 *      这两件事的生命周期不同，不该共用一个开关。
 *    想加调试打印时：把总闸拨 1 → 下面按模块补分闸 →
 *    在各层代码里用分闸包住打印语句，三步即可，其它文件一行都不用改。
 *
 *  ★ 为什么这里还留一道 #error：
 *    万一有人把总闸拨成 1、却没有串口链，编译期就会当场拦下，
 *    而不是等烧录后"串口一个字都没有"再回头查半天——
 *    这与 cfg_check.h 的"配错不让过编译期"是同一套思路。
 ******************************************************************************
 */
#ifndef CFG_PRINT_H
#define CFG_PRINT_H

/* 总闸：0 = 一键关闭全部串口打印。本例业务回复直出，总闸保持 0。
 * ★ 注意：本工程目前【没有】任何代码使用这个宏（业务回复与日志都是直出，
 *   不经过总闸）。把它拨成 1 不会让打印变多，唯一的实际效果是
 *   "关掉串口链的裁剪场景"（回退纯闪烁 / 裸机骨架）会在编译期被下面的闸门拦下。 */
#define UART1_PRINT_MASTER_ENABLE  0

/* 编译期闸门：想开打印，必须先有一条串口链（MOD_UART1_ENABLE，写在 cfg_switch.h）。
 * 接入步骤见 docs/software-engineering/ 的《module_cfg 配置体系与两级开关》文档。 */
#if UART1_PRINT_MASTER_ENABLE && !MOD_UART1_ENABLE
#error "打印总闸要开，必须先有串口链：请先在 cfg_switch.h 打开 MOD_UART1_ENABLE"
#endif

/* --------------------------------------------------------------------------
 *  将来接上串口后，在这里按模块补分闸（形如……）：
 *      #define PER_LED_UART1_PRINTF_ENABLE  (UART1_PRINT_MASTER_ENABLE && 1)
 *      #define APP_LED_UART1_PRINTF_ENABLE  (UART1_PRINT_MASTER_ENABLE && 1)
 *  写成 (总闸 && 1) 的好处：单独关某模块把末尾 1 改 0；总闸拨 0 时全部分闸失效。
 * -------------------------------------------------------------------------- */

#endif /* CFG_PRINT_H */
